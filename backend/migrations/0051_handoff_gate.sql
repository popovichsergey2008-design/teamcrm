-- Приёмка работы («Quality Gatekeeper»).
--
-- Задача уезжает «На проверку» или в «Готово» с незакрытым чек-листом, без
-- единого слова о том, что сделано, и без результата — проверяющий открывает
-- карточку и не понимает, что именно ему принесли. Спрашивать об этом должна
-- система в момент сдачи, а не человек через день в переписке.
--
-- Условия — на уровне компании: это часть договорённости о том, как тут
-- работают, а не личная настройка исполнителя (иначе выключит себе тот,
-- кому проверка мешает). Значения по умолчанию включены сознательно:
-- гейт мягкий — он спрашивает и пускает с отметкой в истории задачи.
ALTER TABLE tenants
    ADD COLUMN gate_require_checklist  BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN gate_require_comment    BOOLEAN NOT NULL DEFAULT TRUE,
    ADD COLUMN gate_require_attachment BOOLEAN NOT NULL DEFAULT TRUE;
