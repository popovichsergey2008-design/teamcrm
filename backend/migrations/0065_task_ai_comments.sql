-- Ответы ИИ живут в той же ленте обсуждения, что и сообщения людей.
--
-- Отдельную таблицу для них заводить незачем: это тот же разговор по задаче, и вся
-- обвязка — права, история, поиск, сохранение после закрытия задачи — уже написана.
-- Нужен ровно один признак: кто это сказал.
--
-- Признак нужен для двух вещей. Первая — человек всегда должен видеть, что ответ
-- сгенерирован, а не написан постановщиком: спутать эти две вещи означает принять
-- догадку за требование. Вторая — уведомления: сообщение ИИ не должно будить всех
-- участников задачи, иначе через неделю обсуждение отключат целиком.
