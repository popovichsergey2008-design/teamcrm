/** Сколько направлений максимум ставим сами: больше — это уже ТЗ на несколько задач. */
export const MAX_AUTO_DIRECTIONS = 3;

/** `$` в конце слова — целиком: «бот» не должен ловить «ботинки», «бд» — «бдительность». */
function hits(text: string, stem: string): number {
  const whole = stem.endsWith('$');
  const word = whole ? stem.slice(0, -1) : stem;
  const esc = word.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const re = new RegExp(`(?<![а-яёa-z0-9])${esc}${whole ? '(?![а-яёa-z0-9])' : ''}`, 'giu');
  return (text.match(re) ?? []).length;
}

/**
 * Направления по тексту, от самого заметного к менее. Пусто — слов не нашлось, и тогда
 * автоматика честно молчит: исполнителя выбирает человек или кнопка «Подобрать».
 */
export function directionsFromText(text: string): Skill[] {
  const t = ` ${String(text ?? '').toLowerCase().replace(/ё/g, 'е')} `;
  const scored = (Object.keys(WORDS) as (keyof typeof WORDS)[])
    .map((skill) => ({
      skill,
      score: WORDS[skill].reduce((sum, w) => sum + hits(t, w.replace(/ё/g, 'е')), 0),
    }))
    .filter((x) => x.score > 0)
    .sort((a, b) => b.score - a.score);
  return scored.slice(0, MAX_AUTO_DIRECTIONS).map((x) => x.skill as Skill);
}

/**
 * Пунктов в тексте — ТЗ это или одно поручение. Считаем строки-пункты («1.», «2)»,
 * «- », «• »). Два и больше разных пункта — повод предложить «разложить по специалистам».
 */
export function listItemsCount(text: string): number {
  return String(text ?? '').split(/\r?\n/).filter((l) => /^\s*(\d{1,2}[.)]|[-•*–])\s+\S/.test(l)).length;
}
