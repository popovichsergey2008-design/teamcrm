-- ТЗ-9, волна 10: служба заботы в мобильной оболочке.
--
-- Телефон добавляет к техническому контексту обращения то, чего у браузера нет:
-- где запущен фронт (браузер / PWA / оболочка), версию нативной оболочки и модель
-- устройства. Специалисту это первые вопросы («у вас приложение или сайт?»,
-- «какой телефон?»), и без них диагностика мобильного бага начинается с гадания.
-- Поля названы поимённо, как и остальные: разрешённый список, а не мешок JSON.
ALTER TABLE support_context
    ADD COLUMN IF NOT EXISTS platform       VARCHAR(16) NULL,   -- web | mobile-web | capacitor
    ADD COLUMN IF NOT EXISTS native_version VARCHAR(40) NULL,   -- версия оболочки (только capacitor)
    ADD COLUMN IF NOT EXISTS device         VARCHAR(80) NULL;   -- модель устройства
