-- Уведомления на телефон приходят, даже когда открыт компьютер.
--
-- Было: push по чатам пропускался, если человек «в сети» — а «в сети» считалось по
-- ЛЮБОМУ открытому соединению. Открытая на компьютере вкладка CRM держит сокет весь
-- день, поэтому телефон не звучал вообще никогда. Жалоба заказчика: «в андроид
-- приложение не приходят оповещения о сообщениях, вообще не приходят».
--
-- Присутствие должно считаться по УСТРОЙСТВУ, а не по человеку: телефон молчит, если
-- человек смотрит в ЭТОТ телефон, и звучит во всех остальных случаях. Оболочка
-- сообщает, открыта она сейчас или свёрнута, — это и храним.
ALTER TABLE mobile_devices
    ADD COLUMN IF NOT EXISTS foreground    BOOLEAN     NOT NULL DEFAULT false,
    -- Когда состояние сообщили в последний раз: устаревшему не верим — приложение
    -- могли убить, не успев сказать «я свернулось».
    ADD COLUMN IF NOT EXISTS foreground_at TIMESTAMPTZ NULL;
