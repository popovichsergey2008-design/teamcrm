-- Запрет ставить встречи на занятое время — личная настройка каждого.
--
-- По умолчанию включён: календарь без этого правила быстро превращается в стопку
-- наложенных друг на друга встреч, где человек физически не может быть на всех.
-- Кому такой порядок мешает (например, тем, кто держит «фоновые» события вроде
-- «работа над проектом» на полдня), выключают его у себя в личном кабинете.
ALTER TABLE users ADD COLUMN calendar_block_overlap BOOLEAN NOT NULL DEFAULT TRUE;
