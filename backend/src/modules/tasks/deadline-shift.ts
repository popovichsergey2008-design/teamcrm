import { endOfLocalDay, nextRun, RecurrenceRule } from './recurrence';

/**
 * «Сделал» — перенос срока на следующую среду 17:00.
 *
 * Правило заказчика дословно: нажал «Сделал» — срок уезжает на СЛЕДУЮЩУЮ среду в
 * 17:00. Считаем в поясе человека и отдельным модулем под тестами, потому что
 * календарная арифметика ошибается молча: «следующая среда» в среду утром — это
 * через неделю, а не сегодня вечером, и заметить такую ошибку можно только через
 * семь дней.
 */

/** Среда: 1 = понедельник … 7 = воскресенье. */
export const SHIFT_WEEKDAY = 3;
/** Конец рабочего дня: до 17:00 успевают посмотреть, после — уже никто не смотрит. */
export const SHIFT_AT_TIME = '17:00';

/**
 * Следующая среда 17:00 после `now` в поясе `tz`.
 *
 * Отсчитываем от КОНЦА текущего дня, а не от текущей минуты: нажатие «Сделал» в среду
 * означает «эту среду закрыл», и срок должен уехать на следующую, а не на сегодняшний
 * вечер. Во все остальные дни это ближайшая среда — она и так после сегодняшнего дня.
 */
export function nextWednesday(now: Date, tz: string): Date {
  const rule: RecurrenceRule = {
    freq: 'weekly',
    weekdays: [SHIFT_WEEKDAY],
    monthday: null,
    intervalDays: null,
    atTime: SHIFT_AT_TIME,
    tz,
  };
  return nextRun(rule, endOfLocalDay(now, tz));
}
