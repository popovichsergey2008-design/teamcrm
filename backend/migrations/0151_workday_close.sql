-- ТЗ-16, волна 7. «Завершить день»: день закрыт до начала следующего рабочего дня.
--
-- Хранится у человека, а не в плане дня: «день закрыт» видят коллеги («Команда
-- сейчас») и уважают уведомления, а план — личный документ на одну дату.

ALTER TABLE users
    -- до этого момента человек «завершил день»; NULL или прошлое — день открыт
    ADD COLUMN workday_closed_until TIMESTAMPTZ NULL,
    -- после «Завершить день» — тихий режим до утра (п. 86); по умолчанию включён
    ADD COLUMN quiet_after_close BOOLEAN NOT NULL DEFAULT TRUE;
