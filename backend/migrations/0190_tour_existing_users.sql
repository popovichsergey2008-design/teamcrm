-- Обучение новичка (#4605, 20.10): само запускается только у новых людей. Кто уже
-- работает в системе, обучение не увидит внезапно — пройти его можно из меню профиля
-- («Обучение»). Новый человек приходит без ключа tour и получает обзор при первом входе.
UPDATE users
   SET ui_prefs = COALESCE(ui_prefs, '{}'::jsonb) || '{"tour": {"auto": false}}'::jsonb
 WHERE ui_prefs IS NULL OR ui_prefs->'tour' IS NULL;
