-- Перенос срока «Сделал» — с подтверждением постановщика.
--
-- Просьба заказчика: у регулярных дел («сделал — до следующей среды») исполнитель
-- должен одним нажатием отодвигать срок на следующую среду 17:00, а постановщик —
-- подтверждать перенос. Без подтверждения это была бы кнопка «продлить себе срок»,
-- и сроки перестали бы значить что-либо.
--
-- Устройство такое же, как у согласования завершения: предложенный срок живёт ПРИ
-- ЗАДАЧЕ до решения, а сам deadline_at не трогаем. Отдельной таблицы нет намеренно —
-- незакрытое предложение всегда одно, а история переносов и так пишется в
-- task_activity.
ALTER TABLE tasks
    -- куда переносим, если постановщик согласится
    ADD COLUMN deadline_shift_to TIMESTAMPTZ NULL,
    -- кто попросил: ему же уходит ответ о решении
    ADD COLUMN deadline_shift_by BIGINT NULL REFERENCES users(id),
    ADD COLUMN deadline_shift_at TIMESTAMPTZ NULL;

-- Ждущих решения задач единицы: индекс только по ним.
CREATE INDEX idx_tasks_deadline_shift ON tasks (tenant_id, deadline_shift_at)
    WHERE deadline_shift_to IS NOT NULL;
