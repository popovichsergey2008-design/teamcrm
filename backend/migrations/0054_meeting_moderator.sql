-- Модератор встреч: повестка до и разбор после.
--
-- Встреча начинается с «так, о чём мы хотели поговорить?» и заканчивается тем, что
-- договорённости живут в чьей-то памяти. Первое лечится повесткой за пять минут,
-- второе — разбором, который у нас уже есть, но о нём знает только тот, кто открыл
-- страницу встречи.

-- Повестка на КОНКРЕТНОЕ начало встречи. Перенесли — соберём заново: повестка,
-- собранная неделю назад, к новому времени успевает устареть.
CREATE TABLE meeting_agendas (
    event_id   BIGINT PRIMARY KEY REFERENCES calendar_events(id) ON DELETE CASCADE,
    tenant_id  BIGINT NOT NULL REFERENCES tenants(id),
    starts_at  TIMESTAMPTZ NOT NULL,
    -- Готовый текст для человека: факты, собранные правилами, и формулировка модели.
    body       TEXT NOT NULL,
    -- Те же факты в исходном виде — чтобы показать повестку, даже если модель молчала,
    -- и чтобы потом можно было понять, откуда взялся пункт.
    facts      JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Из какого события выросла встреча: разбор должен знать, чью повестку он закрывает,
-- а следующая повестка — чем закончилась прошлая встреча этой же серии.
ALTER TABLE meetings
    ADD COLUMN event_id BIGINT NULL REFERENCES calendar_events(id);
CREATE INDEX idx_meetings_event ON meetings (tenant_id, event_id);

-- Создавать ли задачи со встречи сразу.
--
-- Включено по решению заказчика, но с оговоркой в коде: сами создаются ТОЛЬКО те
-- черновики, где модель уверенно назвала и исполнителя, и проект. Остальное остаётся
-- черновиком — «ИИ ничего не создаёт молча» слишком дорого нарушать целиком.
ALTER TABLE tenants
    ADD COLUMN meeting_auto_tasks BOOLEAN NOT NULL DEFAULT TRUE;
