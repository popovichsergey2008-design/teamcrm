-- Кнопка «Поддержка» в левой панели.
--
-- Сотрудник, у которого что-то не работает, должен сообщить об этом одним
-- действием, не разбираясь, в какой проект и кому ставить задачу. Обращение
-- становится обычной задачей в проекте поддержки: у неё есть постановщик
-- (кто обратился), исполнитель (владелец компании), переписка, файлы и
-- статус — ничего нового изобретать не нужно, и ничего не потеряется.
--
-- Какой проект — поддержка, выбирает руководитель в настройках проекта; пока
-- не выбрал, первое обращение заводит проект «Поддержка» само. Один на компанию.
ALTER TABLE projects
    ADD COLUMN is_support BOOLEAN NOT NULL DEFAULT false;
