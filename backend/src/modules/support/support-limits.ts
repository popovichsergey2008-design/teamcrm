/**
 * Пределы частоты в службе заботы (05_SCALING §20).
 *
 * Зачем: коммерческий продукт открыт наружу, и один человек — случайно или нарочно —
 * не должен положить поддержку всем остальным. Двадцать вложений в минуту это не
 * работа, а либо сломанный клиент, либо злоупотребление.
 *
 * Главное правило, из-за которого всё остальное и написано осторожно: **позвать
 * человека можно всегда**. Пределы стоят на потоке сообщений, файлов, просьб о созвоне
 * и обращений к модели — но никогда на эскалации. Человек, которому мы отказали в
 * помощи из-за счётчика, — это худшее, что служба заботы может сделать.
 */

export interface Limit {
  /** Сколько раз можно. */
  times: number;
  /** За сколько секунд. */
  perSeconds: number;
  /** Что сказать, когда предел достигнут. По-человечески и без слова «лимит». */
  say: string;
}

export const LIMITS = {
  /** Сообщения в разговоре: обычная переписка — единицы в минуту. */
  message: {
    times: 30, perSeconds: 300,
    say: 'Слишком много сообщений подряд — переведите дух, через пару минут продолжим.',
  },
  /** Вложения: тяжелее всего и чаще всего именно они. */
  attachment: {
    times: 10, perSeconds: 300,
    say: 'Много файлов подряд. Подождите пару минут — всё присланное уже у нас.',
  },
  /** Просьбы о созвоне: пять за четверть часа — это уже не просьба. */
  call: {
    times: 5, perSeconds: 900,
    say: 'Мы видим вашу просьбу о созвоне. Дайте специалисту ответить.',
  },
  /** Новые обращения: чтобы один человек не заводил их десятками. */
  conversation: {
    times: 5, perSeconds: 3600,
    say: 'Слишком много обращений за час. Продолжайте в уже открытом — мы его видим.',
  },
} satisfies Record<string, Limit>;

export type LimitKind = keyof typeof LIMITS;

/** Ключ счётчика: свой на человека и на вид действия. */
export function limitKey(kind: LimitKind, userId: string): string {
  return `support:rate:${kind}:${userId}`;
}
