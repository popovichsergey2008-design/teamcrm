/**
 * Набор эмодзи для переписки (просьба заказчика: «как в Slack, почти сотня»).
 *
 * Почему списком в коде, а не готовой библиотекой: полный набор Unicode — это полторы
 * тысячи знаков и мегабайт данных, из которых в рабочей переписке используют три
 * десятка. Здесь отобрано то, чем реально отвечают на работе, и к каждому знаку
 * приписаны РУССКИЕ слова для поиска: искать «огонь» по слову «fire» никто не станет.
 *
 * Порядок внутри раздела — от частого к редкому, а не по алфавиту: первые ряды видны
 * без прокрутки, и в них должно лежать то, что ставят чаще всего.
 */

export interface EmojiItem {
  /** Сам знак. */
  e: string;
  /** Слова для поиска: первое — основное название, его же показываем в подсказке. */
  words: string[];
}

export interface EmojiGroup {
  key: string;
  title: string;
  /** Знак на вкладке раздела. */
  icon: string;
  items: EmojiItem[];
}

