-- Слой 5 ТЗ-3: мит остаётся привязанным к разговору.
--
-- Созвон начинают из чата и там же продолжают работать после него. Но итог созвона
-- жил отдельно — в разделе встреч, куда надо специально пойти. В результате половина
-- договорённостей не доходила до тех, кто в разговоре не был: чат молчал, как будто
-- ничего и не происходило.
--
-- Теперь встреча знает свой чат, а в чат после разбора приходит карточка: сколько шёл
-- разговор, о чём договорились и какие задачи предложены.
ALTER TABLE meetings ADD COLUMN chat_id BIGINT NULL REFERENCES chats(id) ON DELETE SET NULL;

-- Сообщение-карточка. Тело остаётся человекочитаемым (в письмах и выгрузках карточки
-- нет), а meeting_id даёт интерфейсу развернуть его в сводку с кнопкой «Открыть разбор».
ALTER TABLE chat_messages ADD COLUMN meeting_id BIGINT NULL REFERENCES meetings(id) ON DELETE SET NULL;
