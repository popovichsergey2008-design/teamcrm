-- Продукт переименован: TeamCRM → ANTHILL.
--
-- В коде и документации название заменено правкой файлов, но справочник уже лежит в
-- базе знаний КАЖДОЙ организации отдельными регламентами — 10 разделов на компанию.
-- Без этой миграции у людей остались бы документы со старым именем, а загрузчик завёл
-- бы рядом такие же с новым: два справочника в одной базе знаний, и помощник цитировал
-- бы то один, то другой.
--
-- Переименование, а не удаление с перезаливкой: у документа есть история правок и
-- ссылки, и терять их из-за смены вывески незачем.

UPDATE regulations
   SET title = replace(title, 'Справочник TeamCRM · ', 'Справочник ANTHILL · '),
       updated_at = now()
 WHERE title LIKE 'Справочник TeamCRM · %';

/*
  Куски поискового индекса переиндексируются заново.

  В каждом куске лежит СНИМОК текста вместе с заголовком — именно его помощник
  показывает как источник ответа. Простое переименование документа их не трогает, и
  поиск ещё долго отвечал бы «Справочник TeamCRM · Задачи». Удаляем; сервис справочника
  при ближайшей сверке увидит раздел без кусков и поставит его в очередь на индексацию.
*/
DELETE FROM knowledge_chunks
 WHERE source_type = 'regulation'
   AND source_id IN (SELECT id FROM regulations WHERE title LIKE 'Справочник ANTHILL · %');

DO $$
DECLARE renamed INT;
BEGIN
  SELECT count(*) INTO renamed FROM regulations WHERE title LIKE 'Справочник ANTHILL · %';
  RAISE NOTICE 'справочник переименован в ANTHILL: разделов %', renamed;
END $$;
