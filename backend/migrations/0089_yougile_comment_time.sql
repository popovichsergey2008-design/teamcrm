-- Время комментариев из YouGile — настоящее, а не момент импорта.
--
-- Заказчик (задача #900): «сообщения не по порядку — между первым и вторым
-- сообщением Юры висят старые сообщения по Краснодару, которые он делал давным
-- давно». Разбор показал: YouGile не отдаёт у сообщения чата поле timestamp, и
-- комментарий записывался со временем ИМПОРТА. Старое сообщение, приехавшее
-- вебхуком позже, вставало в переписку «сегодняшним» — посреди свежих.
--
-- Настоящее время у YouGile лежит в самом id сообщения: это миллисекунды
-- создания (у нас — хвост external_id после «:»). Ставим его всем уже
-- импортированным комментариям; дальше код делает то же при импорте.
--
-- Только YouGile и только правдоподобные значения: 13 цифр, между 2015 годом
-- и сейчас. У Битрикса номера комментариев устроены иначе, их не трогаем.
UPDATE task_comments c
   SET created_at = to_timestamp(split_part(r.external_id, ':', 2)::bigint / 1000.0)
  FROM external_refs r
  JOIN integration_connections ic ON ic.id = r.connection_id
 WHERE r.entity_type = 'comment'
   AND r.local_id = c.id
   AND ic.provider = 'yougile'
   AND split_part(r.external_id, ':', 2) ~ '^[0-9]{13}$'
   AND to_timestamp(split_part(r.external_id, ':', 2)::bigint / 1000.0)
       BETWEEN TIMESTAMPTZ '2015-01-01' AND now();
