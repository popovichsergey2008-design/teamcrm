/** Все знаки одним списком — для поиска и для проверки «знаем ли мы такой». */
export const ALL_EMOJI: EmojiItem[] = EMOJI_GROUPS.flatMap((g) => g.items);

/** Быстрый ряд в меню сообщения: то, чем отвечают чаще всего. */
export const QUICK_REACTIONS = ['👍', '❤️', '🔥', '👏', '😁', '🤔'];

/**
 * Поиск по словам.
 *
 * Совпадением считаем НАЧАЛО слова, а не вхождение: по «раз» должно находиться
 * «разработка», но не «образование». Пустой запрос — весь набор, чтобы окно поиска
 * не превращалось в пустой экран.
 */
export function searchEmoji(query: string, items: readonly EmojiItem[] = ALL_EMOJI): EmojiItem[] {
  const q = query.trim().toLowerCase().replace(/ё/g, 'е');
  if (!q) return [...items];
  return items.filter((it) => it.e === q || it.words.some((w) => {
    const word = w.toLowerCase().replace(/ё/g, 'е');
    return word.startsWith(q) || word.split(' ').some((part) => part.startsWith(q));
  }));
}

const RECENT_KEY = 'anthill.emoji.recent';

/** Недавние: человек ставит одно и то же, и это должно лежать первым. */
export function recentEmoji(storage: Pick<Storage, 'getItem'> = localStorage): string[] {
  try {
    const raw = JSON.parse(storage.getItem(RECENT_KEY) ?? '[]');
    return Array.isArray(raw) ? raw.filter((x) => typeof x === 'string').slice(0, 16) : [];
  } catch { return []; }
}

export function rememberEmoji(emoji: string, storage: Pick<Storage, 'getItem' | 'setItem'> = localStorage): string[] {
  const next = [emoji, ...recentEmoji(storage).filter((x) => x !== emoji)].slice(0, 16);
  try { storage.setItem(RECENT_KEY, JSON.stringify(next)); } catch { /* приват-режим */ }
  return next;
}
