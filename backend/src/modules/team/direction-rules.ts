/**
 * Направления задачи по её тексту — правилами, без модели (задачи #1295, #1363).
 *
 * Заказчик хочет, чтобы исполнитель выставлялся САМ, как только понятно, для кого
 * задача: «API» — бэкенду, «кнопка на странице» — фронтенду, «статья» — копирайтеру.
 * А 23.09 он же решил, что модель дёргаем только по кнопке — иначе токены уходят на
 * каждую создаваемую задачу. Правила по словам дают автоматику бесплатно; для
 * непонятных случаев остаётся кнопка «Подобрать» с моделью.
 *
 * Слова — основы: «страниц» ловит «страница», «страницу», «страницы». Граница слова
 * задаётся явно — `\b` в JS не видит кириллицу (старые грабли проекта).
 *
 * Чистая функция; проверяется тестом рядом.
 */

