/**
 * Размер шрифта интерфейса.
 *
 * Заказчик: «сделать возможность увеличения шрифта для пользователей с плохим
 * зрением». Меняем не одну надпись, а весь интерфейс: множитель `--fs-scale` стоит
 * в каждом размере шрифта — и в токенах, и в правилах, где размер записан числом.
 * Коробки (отступы, высоты кнопок) остаются прежними: это увеличение ТЕКСТА, как в
 * настройках браузера, а не масштаб всей страницы — масштаб ломает `vh`-раскладки
 * и прижатые к краям панели.
 *
 * Значение живёт на устройстве (localStorage), а не в учётной записи: плохо видно
 * человеку за конкретным экраном — на большом мониторе тот же человек ставит обычный
 * размер. Ровно так же у нас хранится свёрнутая панель и выбранная тема.
 */

const KEY = 'teamcrm.fontSize';
/** Базовый размер интерфейса: от него и считается множитель. */
export const BASE_SIZE = 14;
/** Что предлагаем на выбор. Мельче 12 — нечитаемо, крупнее 20 — ломается вёрстка таблиц. */
export const FONT_SIZES = [12, 14, 16, 18, 20];

export function fontSize(): number {
  const raw = Number(localStorage.getItem(KEY));
  return FONT_SIZES.includes(raw) ? raw : BASE_SIZE;
}

/** Применить размер к документу. Отдельно от сохранения — им же чиним первый кадр. */
function apply(px: number): void {
  document.documentElement.style.setProperty('--fs-scale', String(px / BASE_SIZE));
}

export function setFontSize(px: number): void {
  const size = FONT_SIZES.includes(px) ? px : BASE_SIZE;
  try { localStorage.setItem(KEY, String(size)); } catch { /* приватный режим — переживём */ }
  apply(size);
}

/**
 * Поставить сохранённый размер ДО первой отрисовки.
 *
 * Иначе интерфейс моргнёт обычным шрифтом и перестроится — тому, кто увеличил шрифт
 * из-за зрения, это моргание заметнее всех.
 */
export function initFontScale(): void {
  try { apply(fontSize()); } catch { /* нет localStorage — остаётся обычный размер */ }
}
