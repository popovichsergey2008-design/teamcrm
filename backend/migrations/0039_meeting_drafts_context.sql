-- Черновик задачи со встречи: колонка доски и постановщик.
--
-- Проект в черновике был, но заполнялся только тем, что выбрали при загрузке
-- записи, — названный вслух проект не учитывался. Колонки не было вовсе,
-- и задача падала в первую попавшуюся, даже когда на встрече прямо сказали,
-- куда её класть.
--
-- Постановщиком становился тот, кто нажал «создать», а не тот, кто поручил
-- на встрече. Для истории задачи это неверно: поручение принадлежит тому,
-- кто его дал.

ALTER TABLE meeting_task_drafts
    ADD COLUMN column_id   BIGINT NULL REFERENCES board_columns(id),
    ADD COLUMN column_hint VARCHAR(120) NULL,   -- название колонки, как прозвучало
    ADD COLUMN project_hint VARCHAR(120) NULL,  -- название проекта, как прозвучало
    ADD COLUMN author_id   BIGINT NULL REFERENCES users(id),
    ADD COLUMN author_hint VARCHAR(120) NULL;   -- кто поручил, как прозвучало
