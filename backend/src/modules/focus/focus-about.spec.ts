import { aboutLine } from './focus-day.service';

describe('#4768: пояснение к пункту «Фокуса дня» из описания', () => {
  it('первая содержательная строка, без разметки', () => {
    const d = '<p>ВАУ-ФИЧА 1: Экран финала созвона «Магический запуск задач» (Audio-Proof Tasks)</p><p>Как сейчас: черновик…</p>';
    expect(aboutLine(d, 'Важно внедрить после мита')).toBe('ВАУ-ФИЧА 1: Экран финала созвона «Магический запуск задач» (Audio-Proof Tasks)');
  });
  it('повтор названия и короткие строки пропускаем, длинное обрезаем', () => {
    expect(aboutLine('<p>Важно внедрить после мита</p><p>ок</p><p>Сделать экран итогов</p>', 'Важно внедрить после мита')).toBe('Сделать экран итогов');
    expect(aboutLine(null, 'x')).toBeNull();
    expect(aboutLine(`<p>${'а'.repeat(300)}</p>`, 'x')!.length).toBe(158);
  });
});
