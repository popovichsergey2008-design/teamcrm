-- Отметки о прочтении переписки задачи (ТЗ-7, разд. 17 — «Просмотрено»).
--
-- Заказчик показал снимок чужого мессенджера со строкой «✓✓ Просмотрено: имя и ещё 1»
-- и попросил так же. Хранить отметку на каждое сообщение и каждого человека — это
-- строка на каждую пару, то есть сотни тысяч строк на активном проекте ни за чем:
-- переписку читают подряд. Поэтому храним ОДНУ отметку на человека и задачу —
-- последнее прочитанное им сообщение. Кто видел сообщение N, вычисляется сравнением.
--
-- Отметка только ползёт вверх (GREATEST при обновлении): «прочитал и прокрутил
-- назад» не должно снимать уже показанное отправителю подтверждение.
-- Почему не переиспользуем task_reads: там отметка о ПРОСМОТРЕ КАРТОЧКИ (метка времени
-- по открытию), и на ней держатся красные счётчики непрочитанного. Отмечать её из чата
-- значило бы гасить новости о переносах и правках задачи всякий раз, когда человек
-- просто читает переписку. Вопросы разные — и таблицы разные.
CREATE TABLE task_comment_reads (
    tenant_id    BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    task_id      BIGINT NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    last_read_id BIGINT NOT NULL,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, task_id, user_id)
);

-- Спрашивают всегда одно: кто и докуда прочитал ЭТУ задачу.
CREATE INDEX idx_task_reads_task ON task_comment_reads (tenant_id, task_id);
