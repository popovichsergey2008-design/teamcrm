import { splitPhrase } from './focus-wave2.service';

describe('первый день: фраза → задачи без модели (#4891, п. 11)', () => {
  it('делит по «;», строкам и «потом»', () => {
    expect(splitPhrase('дописать отчёт; созвон с клиентом потом проверить макет')).toEqual(['Дописать отчёт', 'Созвон с клиентом', 'Проверить макет']);
    expect(splitPhrase('1. Счёт\n2. Письмо Ивану')).toEqual(['Счёт', 'Письмо Ивану']);
  });
  it('одна фраза — одна задача', () => {
    expect(splitPhrase('подготовить презентацию для инвесторов')).toEqual(['Подготовить презентацию для инвесторов']);
  });
});
