-- Служба заботы становится ВЕНДОРСКОЙ: отвечает разработчик продукта, а не сам клиент.
--
-- До этой миграции поддержка была внутренним helpdesk: в каждой организации свои
-- дежурные, свои известные проблемы, своя сводка — и, что хуже всего, настройки всего
-- этого видел любой владелец клиентской организации. Для коробочного продукта это
-- неверно дважды: клиент не должен ни настраивать нашу поддержку, ни видеть её кухню.
--
-- Модель после миграции:
--   • одна организация помечена как ПЛАТФОРМА (вендор, разработчик CRM);
--   • её сотрудники, перечисленные в platform_staff, — техподдержка продукта;
--   • обращение по-прежнему принадлежит организации обратившегося, но отвечает на него
--     персонал платформы, и вся «кухня» (очередь, дежурные, известные проблемы, сбои,
--     сводка, справочник) видна только ему.
--
-- Клиентские настройки поддержки при этом исчезают, а не переезжают: их не должно быть.

/*
  Организация-вендор.

  Флагом на существующей таблице, а не отдельной «таблицей платформы»: платформа —
  такая же организация со своими людьми, задачами и досками, просто у неё есть
  дополнительная роль в продукте. Частичный уникальный индекс держит инвариант
  «платформа ровно одна» — две платформы означали бы две разные службы заботы.
*/
ALTER TABLE tenants ADD COLUMN is_platform BOOLEAN NOT NULL DEFAULT FALSE;
CREATE UNIQUE INDEX uniq_tenant_platform ON tenants (is_platform) WHERE is_platform;

/*
  Персонал платформы — техотдел.

  `role`: admin настраивает службу (кто дежурит, известные проблемы, сбои), agent
  отвечает в обращениях. `active` — «дежурит сейчас»: снятый с дежурства сотрудник
  остаётся в списке и не теряет историю, но новые обращения ему не показываются.

  Ключ по user_id, а не (tenant_id, user_id): человек платформы един, и запись о нём
  должна быть одна независимо от того, как менялась его организация.
*/
CREATE TABLE platform_staff (
    user_id    BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    tenant_id  BIGINT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    role       VARCHAR(16) NOT NULL DEFAULT 'agent',   -- admin | agent
    active     BOOLEAN NOT NULL DEFAULT TRUE,
    skills     TEXT[] NOT NULL DEFAULT '{}',
    created_by BIGINT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_platform_staff_live ON platform_staff (active, tenant_id);

/*
  Системные регламенты: справочник по продукту.

  Справочник грузится в базу знаний каждой организации — иначе помощник не найдёт его
  своим же поиском. Но это НАШ текст: клиент не должен его править, а наша выкладка не
  должна затирать его правки. Пометка делает его в базе знаний read-only.
*/
ALTER TABLE regulations ADD COLUMN is_system BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE regulations SET is_system = TRUE WHERE title LIKE 'Справочник TeamCRM · %';
