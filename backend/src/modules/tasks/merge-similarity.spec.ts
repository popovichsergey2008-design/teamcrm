import { joinDescriptions, mergeChecklists, percent, scoreTask, similarity } from './merge-similarity';

describe('поиск дублей и склейка при объединении задач', () => {
  it('похожие названия набирают больше, чем случайно общие слова', () => {
    const chat = similarity('Добавить чат в карточку задачи', 'Добавить AI-чат в карточку задачи');
    const alien = similarity('Добавить чат в карточку задачи', 'Оплатить хостинг за сентябрь');
    expect(chat).toBeGreaterThan(0.6);
    expect(alien).toBe(0);
  });

  it('пустой текст не даёт ложного совпадения', () => {
    expect(similarity('', 'Добавить чат')).toBe(0);
    expect(similarity('в и на', 'в и на')).toBe(0); // одни служебные слова — сравнивать нечего
  });

  it('название весит больше описания и объясняет причину', () => {
    const base = { id: '1', title: 'Добавить чат в карточку задачи', description: 'Обсуждение внутри задачи' };
    const near = scoreTask(base, { id: '2', title: 'Добавить чат в карточку', description: null });
    const far = scoreTask(base, { id: '3', title: 'Купить кофе', description: 'Обсуждение внутри задачи' });

    expect(near.score).toBeGreaterThan(far.score);
    expect(near.reason).toBe('почти одинаковые названия');
    expect(percent(near.score)).toBeGreaterThan(50);
    // процент никогда не показывает ни 0, ни 100: обе цифры человек читает как факт
    expect(percent(0)).toBe(1);
    expect(percent(1)).toBe(99);
  });

  it('чек-листы склеиваются без дублей, свои пункты идут первыми', () => {
    const out = mergeChecklists(
      ['Добавить чат в карточку', 'Подключить AI'],
      ['добавить чат в карточку ', 'Подключить AI', 'Написать тесты'],
    );
    expect(out).toEqual(['Добавить чат в карточку', 'Подключить AI', 'Написать тесты']);
  });

  it('разные глаголы при двух словах НЕ склеиваются — это защита, а не промах', () => {
    // «Добавить чат» и «Реализовать чат» без модели неотличимы от «Написать тесты»
    // и «Написать документацию»: общее слово одно из двух. Склеивать такое опасно —
    // потерянный шаг работы дороже лишней строки. Синонимы разбирает ИИ, когда он есть.
    expect(mergeChecklists(['Добавить чат'], ['Реализовать чат']))
      .toEqual(['Добавить чат', 'Реализовать чат']);
    expect(mergeChecklists(['Написать тесты'], ['Написать документацию']))
      .toEqual(['Написать тесты', 'Написать документацию']);
  });

  it('чек-лист не теряет непохожие шаги и не боится пустых строк', () => {
    expect(mergeChecklists(['Сверстать форму'], ['  ', 'Проверить на телефоне']))
      .toEqual(['Сверстать форму', 'Проверить на телефоне']);
  });

  it('описания склеиваются с подписью, а одинаковое не повторяется', () => {
    expect(joinDescriptions('Первое', '', '10')).toBe('Первое');
    expect(joinDescriptions('', 'Второе', '10')).toBe('Второе');
    expect(joinDescriptions('Нужен чат в задаче', 'Нужен чат в задаче', '10')).toBe('Нужен чат в задаче');
    expect(joinDescriptions('Нужен чат', 'Ещё бы уведомления', '10'))
      .toBe('Нужен чат\n\n— из задачи #10:\nЕщё бы уведомления');
  });
});
