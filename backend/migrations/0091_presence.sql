-- Присутствие людей — для Chat Bar (ТЗ-5, этап 1).
--
-- Сейчас про человека известно только «в сети / не в сети». Chat Bar показывает
-- больше: «был 12 минут назад», «занят», «отошёл», «на мите». Первое — время
-- последнего соединения; второе и третье человек ставит себе САМ (заказчик:
-- автоматики по бездействию не нужно); «на мите» считается от живых созвонов и
-- в базе не хранится.
ALTER TABLE users
    ADD COLUMN last_seen_at    TIMESTAMPTZ NULL,
    -- 'busy' | 'away' | NULL (как обычно). Ставится и снимается вручную.
    ADD COLUMN presence_status VARCHAR(8) NULL;
