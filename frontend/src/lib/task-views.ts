/**
 * Виды задач — «кто я в этой задаче».
 *
 * Один словарь на всю систему: те же четыре слова стоят и в кнопке «Мои задачи» на
 * доске, и во вкладках раздела «Задачи». Раньше они назывались по-разному («Мне»,
 * «От меня» на доске против «Мне», «От меня», «Наблюдаю» в реестре) и означали не
 * совсем одно и то же: «Мне» на доске включало работу соисполнителем, а в реестре —
 * тоже, но узнать об этом было неоткуда.
 *
 * Разделение именно такое, потому что это разные роли в работе, и путать их дорого:
 * «Делаю» — что спросят с меня, «Поручил» — что я жду от других, «Помогаю» — где я
 * вторая пара рук, «Наблюдаю» — где я вообще ни за что не отвечаю.
 */

import type { IconName } from '../components/Icon';

export type TaskView = 'doing' | 'helping' | 'delegated' | 'watching';

export interface TaskViewDef {
  key: TaskView;
  label: string;
  /** Подпись под названием: человек должен понимать, ЧТО именно перед ним. */
  hint: string;
  icon: IconName;
}

/** Порядок — по частоте обращения: своя работа, поручения, помощь, наблюдение. */
export const TASK_VIEWS: TaskViewDef[] = [
  { key: 'doing', label: 'Делаю', hint: 'я исполнитель', icon: 'user' },
  { key: 'delegated', label: 'Поручил', hint: 'я поставил, делает кто-то другой', icon: 'send' },
  { key: 'helping', label: 'Помогаю', hint: 'я соисполнитель', icon: 'users' },
  { key: 'watching', label: 'Наблюдаю', hint: 'слежу, выполнять не обязан', icon: 'eye' },
];

export function taskViewLabel(key: string): string {
  return TASK_VIEWS.find((v) => v.key === key)?.label ?? '';
}

/**
 * Старые названия срезов.
 *
 * `assigned` и `created` жили в памяти браузера у каждого, кто пользовался фильтром на
 * доске, `mine` — в ссылках на реестр. Молча уронить их значит открыть человеку не тот
 * список, чем он пользовался вчера.
 */
export const LEGACY_VIEWS: Record<string, TaskView> = {
  mine: 'doing',
  assigned: 'doing',
  created: 'delegated',
};
