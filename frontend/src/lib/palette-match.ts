/**
 * Отбор и порядок строк в командной строке (Ctrl+K).
 *
 * Вынесено из компонента, потому что это единственная часть палитры, которая может
 * тихо ошибаться: человек видит список и считает, что «ничего не нашлось», хотя
 * совпадение было — просто уехало вниз. Такое проверяется тестом, а не глазами.
 */

/** Ё и е людям при наборе неразличимы, а строкам — различимы. */
export const norm = (s: string) => s.toLowerCase().replace(/ё/g, 'е').trim();

/**
 * Насколько хорошо строка отвечает запросу: 0 — начало названия, 1 — начало слова,
 * 2 — где-то внутри, null — не подходит. Меньше значит выше в списке.
 *
 * Порядок именно такой, потому что при вводе «мар» человек ждёт сверху «Маркетинг»,
 * а не «Ремарки по договору».
 */
export function score(title: string, query: string): number | null {
  const q = norm(query);
  if (!q) return 0;
  const t = norm(title);
  const i = t.indexOf(q);
  if (i < 0) return null;
  if (i === 0) return 0;
  const prev = t[i - 1];
  return prev === ' ' || prev === '·' || prev === '-' || prev === '«' ? 1 : 2;
}
