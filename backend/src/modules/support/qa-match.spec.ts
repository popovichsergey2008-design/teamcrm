import { matchQa, normalizeQa, QaEntry, stemQa, tokensQa } from './qa-match';
import data from './qa-base.data.json';

// Проверяем на настоящей базе (лист «Приложение» таблицы заказчика, #4837), а не на
// выдуманных примерах: порог уверенности подобран именно под неё.
const BASE = data as QaEntry[];
const idOf = (text: string) => matchQa(text, BASE)?.entry.id ?? null;

describe('qa-match: база «вопрос — ответ» для Отдела заботы', () => {
  it('нормализация: регистр, ё → е, знаки препинания', () => {
    expect(normalizeQa('  Нужна оплата по СЧЁТУ — для юрлица?! ')).toBe('нужна оплата по счету для юрлица');
    expect(normalizeQa('Есть ли API/вебхуки?')).toBe('есть ли api вебхуки');
  });

  it('основа слова: разные формы сходятся, короткие слова не трогаем', () => {
    expect(stemQa('задачу')).toBe(stemQa('задачи'));
    expect(stemQa('перенести')).toBe(stemQa('перенос'));
    expect(stemQa('api')).toBe('api');
    // служебные слова и название продукта не участвуют в сравнении
    expect(tokensQa('Как можно в Qevo поставить задачу?')).toEqual(tokensQa('поставить задачу'));
  });

  it('вопрос дословно — его ответ', () => {
    expect(idOf('Как поставить задачу голосом?')).toBe('A-091');
    expect(idOf('Есть ли подзадачи?')).toBe('A-267');
    expect(idOf('Можно ли выгрузить все данные из Qevo?')).toBe('A-250');
  });

  it('«другая формулировка» из таблицы — тот же ответ', () => {
    expect(idOf('надиктовать задачу')).toBe('A-091');
    expect(idOf('вложенные задачи')).toBe('A-267');
    expect(idOf('кастомные поля')).toBe('A-268');
  });

  it('пересказ своими словами — тот же ответ', () => {
    expect(idOf('а можно у вас поставить задачу голосом?')).toBe('A-091');
    expect(idOf('Подзадачи есть?')).toBe('A-267');
    expect(idOf('хочу выгрузить все данные')).toBe('A-250');
    expect(idOf('почему задача не закрывается')).toBe('A-039');
  });

  it('ответ команды из таблицы 13.11 — вместо «уточню»', () => {
    // до 13.11 у A-238 ответа команды не было (handoff); Юрий вписал его в лист «Приложение»
    const hit = matchQa('нужна оплата по счету для юрлица', BASE);
    expect(hit?.entry.id).toBe('A-238');
    expect(hit?.entry.handoff).toBe(false);
    expect(hit?.entry.answer).toMatch(/только картой/i);
    // правка команды не перебивает сверенное с продуктом: подзадачи уже есть
    expect(BASE.find((e) => e.id === 'A-267')?.answer).toMatch(/^Да\./);
    expect(BASE.find((e) => e.id === 'A-239')?.answer).toMatch(/Отдельных тарифов ИИ больше нет/);
  });

  it('вопрос не из базы — null, отвечает модель', () => {
    expect(idOf('какая сегодня погода в москве')).toBeNull();
    expect(idOf('')).toBeNull();
    expect(idOf('???')).toBeNull();
  });

  it('одно общее слово — не совпадение', () => {
    // делит с «Есть ли подзадачи?» только «подзадачи», а спрашивает о другом
    expect(idOf('подзадачи не создаются у сотрудника')).not.toBe('A-267');
  });

  it('лишнее слово в сообщении — суть вопроса, без него не отвечаем', () => {
    // делит «поставить» и «задачу» с «поставленными задачами», но спрашивает о сроке
    expect(idOf('Как поставить срок задаче?')).not.toBe('A-133');
  });

  it('жалоба с «не» не путается с вопросом о функции', () => {
    // «вложения» и «вложенные задачи» сходятся по основе, но это поломка, а не подзадачи
    expect(idOf('У меня вложения не открываются в задаче')).toBeNull();
    expect(idOf('микрофон не работает')).toBe('A-092');
  });

  it('одна и та же формулировка у нескольких вопросов — не угадываем', () => {
    // «чек-лист» записан в «других формулировках» и у A-128, и у A-319
    expect(idOf('чек-лист')).toBeNull();
  });

  it('длинный рассказ о своей ситуации — к модели, а не шаблоном', () => {
    expect(idOf(
      'вчера коллега поставил задачу голосом в проект маркетинга, а сегодня утром я открыл доску '
      + 'и не вижу её ни в одной колонке, хотя фильтры сброшены и проект выбран правильный',
    )).toBeNull();
  });

  it('каждый вопрос базы узнаётся сам и не уводит к чужому ответу', () => {
    for (const e of BASE) expect(idOf(e.question)).toBe(e.id);
    for (const e of BASE) {
      for (const a of e.aliases) {
        const got = idOf(a);
        if (got) expect(got).toBe(e.id);
      }
    }
  });
});
