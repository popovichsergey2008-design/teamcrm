/**
 * Черта «Непрочитанные сообщения» — как в Telegram.
 *
 * Открыв чат с цифрой «3», человек должен видеть, КАКИЕ три: без черты он ищет их
 * глазами по всей ленте, а найдя две, не уверен насчёт третьей. Заказчик сказал
 * прямо: «непонятно, какое сообщение непрочитанное, надо как-то его выделять».
 *
 * Сервер к этому моменту уже пометил чат прочитанным (тем же запросом, что отдал
 * ленту), поэтому границу считаем из того, что знали ДО открытия: цифра из списка
 * чатов. Непрочитанные — это последние N чужих сообщений ленты: сервер считает их
 * ровно так же (чужие после отметки «был здесь»), а лента идёт по времени.
 */

export interface UnreadCandidate {
  id: string | number;
  author_id: string | number | null;
}

/**
 * Первое непрочитанное сообщение — перед ним рисуется черта.
 *
 * `null` — черты нет: непрочитанного не было или ленту открыли без цифры. Если
 * непрочитанных больше, чем чужих сообщений на экране (лента подгружает только
 * хвост), черта встаёт перед первым чужим — всё видимое и есть новое.
 */
export function firstUnreadId(
  messages: UnreadCandidate[],
  unread: number,
  meId: string | number | null | undefined,
): string | null {
  if (!unread || unread <= 0) return null;
  const others = messages.filter((m) => String(m.author_id) !== String(meId ?? ''));
  if (!others.length) return null;
  const first = others[Math.max(0, others.length - unread)];
  return String(first.id);
}
