-- 29.10, заказчик: «у существующих сейчас уберём обучалку, только у новых оставим».
--
-- 0190 и 0197 выключали обучение и первый запуск только тем, у кого ключа ещё не было.
-- Кто пришёл после 20–22.10, получил их включёнными, и подсказки разделов (#4632)
-- продолжали всплывать. Теперь — всем, кто есть в базе на момент выкладки:
--   tour.auto = false  — сам не запускается (пройденное `done` сохраняем);
--   welcome.done       — первый запуск пройден, начатый Qevo-бот (`bot`) закрыт.
-- Вручную оба запускаются из меню профиля, как и раньше. Новые люди приходят без этих
-- ключей и видят обучение при первом входе.
UPDATE users
   SET ui_prefs = COALESCE(ui_prefs, '{}'::jsonb)
       || jsonb_build_object('tour', COALESCE(ui_prefs->'tour', '{}'::jsonb) || '{"auto": false}'::jsonb)
       || jsonb_build_object('welcome', (COALESCE(ui_prefs->'welcome', '{}'::jsonb) - 'bot') || '{"done": true}'::jsonb);
