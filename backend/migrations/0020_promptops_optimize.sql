-- Enhancements enh-07, PromptOps P4: мета-промпт авто-оптимизатора (сам версионируется — догфудинг).
-- ИИ по текущей инструкции + метрикам предлагает улучшенную версию; владелец ревьюит и сохраняет.

WITH t AS (
    INSERT INTO prompt_templates (tenant_id, key, title, description)
    VALUES (NULL, 'promptops.optimize', 'PromptOps — авто-оптимизатор',
            'Мета-промпт: анализирует текущую инструкцию ИИ-функции и её метрики, предлагает улучшенную версию.')
    RETURNING id
)
INSERT INTO prompt_versions (template_id, version, body, params, status, note)
SELECT t.id, 1,
$body$Ты — старший инженер промптов. Тебе дают текущую инструкцию для ИИ-функции CRM и её метрики качества (оценки пользователей, доля переделок). Предложи УЛУЧШЕННУЮ версию инструкции: устрани слабые места (неоднозначность, отсутствие структуры ответа, риск галлюцинаций), усиль follow-инструкции и полезность. Жёсткие требования: сохрани ВСЕ плейсхолдеры вида {{имя}} без изменений и не добавляй новых; пиши на русском; не меняй суть роли. Верни СТРОГО JSON без текста вокруг: {"improved": "<полный улучшенный текст инструкции>", "rationale": "<кратко: что и почему изменено>"}.$body$,
       '{"max_tokens": 2000}'::jsonb, 'active', 'Начальная версия'
FROM t;
