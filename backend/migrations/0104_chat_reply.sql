-- Ответ на сообщение в чатах — как в Telegram (ТЗ-7, разд. 5).
--
-- Ветки у нас уже есть, и они решают ДРУГУЮ задачу: увести длинное обсуждение в
-- сторону, чтобы оно не растягивало ленту. Обычный ответ — про другое: реплика
-- остаётся в общем разговоре, но видно, кому она адресована. Заказчик попросил оба
-- и подчеркнул: они должны работать вместе, а не вместо друг друга.
--
-- Отличаются одним полем: `thread_root_id` уводит сообщение из ленты, `reply_to_id`
-- оставляет в ней и добавляет шапку с цитатой. У задач это устроено ровно так же
-- (task_comments, миграции 0066 и 0101) — держим единое устройство.
ALTER TABLE chat_messages
    ADD COLUMN reply_to_id BIGINT NULL REFERENCES chat_messages(id) ON DELETE SET NULL,
    -- выделенный человеком кусок: спорят обычно об одном абзаце, а не обо всём тексте
    ADD COLUMN reply_excerpt VARCHAR(600) NULL;
