/**
 * Промт проверки выполнения задачи.
 *
 * Отдельным файлом, потому что это не код, а текст, который правят чаще кода:
 * от каждого его слова зависит, будет ли проверка полезной или превратится в
 * вежливое «молодец». Здесь же записаны причины, по которым он именно такой.
 *
 * Главные правила, вытекающие из живого опыта:
 *
 * 1. Проверяющий НЕ ХВАЛИТ. Задача ИИ — найти расхождение между тем, что просили,
 *    и тем, что показали. Ответ «всё хорошо» без доказательств бесполезен: ради него
 *    никто кнопку не нажимает.
 *
 * 2. Каждый вывод — со ссылкой на источник: пункт чек-листа, слова из переписки,
 *    имя файла, что видно на снимке. Без источника это гадание, а гадание в отчёте
 *    о проверке хуже отсутствия проверки.
 *
 * 3. «Не могу проверить» — законный и частый ответ. Половина задач проверяется
 *    только руками (позвонить, посмотреть на проде, спросить клиента), и модель
 *    обязана честно сказать это и подсказать, ЧТО именно посмотреть человеку.
 *
 * 4. Никаких выдумок. Если в задаче нет ни файлов, ни переписки, ни отметок в
 *    чек-листе — сделать вывод не из чего, и это тоже ответ.
 *
 * 5. По-русски и коротко. Отчёт читают между делами, а не изучают.
 */

