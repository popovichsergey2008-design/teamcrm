/**
 * Буквы на аватаре без фото (просьба заказчика): две, а не одна и не «#».
 *
 * Один знак различал плохо: у «Сергея» и «Светланы» одинаковое «С», а все группы и
 * каналы были одним и тем же «#» — в свёрнутой панели чатов их приходилось угадывать.
 *
 * Два слова и больше — первые буквы первых двух («Boris Chest» → «BC», «TEAM PRO» →
 * «TP»); одно слово — две первые буквы («Константин» → «Ко», «ОТЧЕТЫ» → «От»).
 * Слова без букв в начале («#общий», «— проект») пропускаем до первой буквы, предлоги
 * и союзы после первого слова не считаем.
 */
/** Предлоги и союзы второй буквой не берём: «Группа по разработке» — «ГР», а не «ГП». */
const SERVICE = new Set(['по', 'и', 'в', 'во', 'на', 'для', 'с', 'со', 'к', 'о', 'об', 'от', 'за', 'из', 'у', 'the', 'of', 'and', 'for', 'a']);

export function initialsOf(name: string | null | undefined): string {
  const words = String(name ?? '')
    .split(/\s+/)
    .map((w) => w.replace(/^[^\p{L}\p{N}]+/u, ''))
    .filter(Boolean)
    .filter((w, i) => i === 0 || !SERVICE.has(w.toLowerCase()));
  if (!words.length) return '?';
  if (words.length === 1) {
    const w = [...words[0]];
    return (w[0] ?? '').toUpperCase() + (w[1] ?? '').toLowerCase();
  }
  return ([...words[0]][0] + [...words[1]][0]).toUpperCase();
}
