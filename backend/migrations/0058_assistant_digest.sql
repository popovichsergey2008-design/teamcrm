--
-- Живая проверка показала: 190 напоминаний за четыре дня, по 8–10 в день на человека,
-- реакция — 14 нажатий «скрыть». Один сотрудник получил 35 сообщений «срок прошёл»
-- за три дня по одним и тем же задачам: повод гасился на сутки и наутро возникал
-- снова. Читать такое перестают, а вместе с шумом теряются и редкие важные сообщения.
--
-- Отсюда две правки. Повод теперь живёт одной строкой и повторяется по нарастающей
-- паузе, а не ежедневно. И вместо россыпи уколов в течение дня человек получает одну
-- сводку в начале своего рабочего дня.

-- Сколько раз об этом уже напоминали и когда в последний раз. По ним считается,
-- пора ли повторять: 1-й раз сразу, дальше через день, три дня, неделю, две.
ALTER TABLE assistant_pings ADD COLUMN repeats     INT NOT NULL DEFAULT 1;
ALTER TABLE assistant_pings ADD COLUMN last_sent_at TIMESTAMPTZ NULL;

-- Существующим строкам проставляем время создания: иначе первый же проход посчитает
-- их «никогда не отправленными» и повторит всё разом — ровно то, от чего уходим.
UPDATE assistant_pings SET last_sent_at = created_at WHERE last_sent_at IS NULL;

