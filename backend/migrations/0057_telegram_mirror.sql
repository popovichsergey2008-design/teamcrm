-- Дублирование почтовых уведомлений в Telegram.
--
-- Почта у нас — единственный внешний канал, и он ненадёжен по причинам вне кода:
-- ключ внешнего сервиса привязан к списку IP, домен ждёт MX, письмо может уйти
-- в спам. Человек узнаёт о новой задаче через час или не узнаёт вовсе.
-- Тот же текст, отправленный в личный чат с ботом, доходит за секунду.
--
-- Дублируем в момент разбора очереди, а не в доменных сервисах: так в бота
-- попадает ВСЁ, что вообще уходит на почту, включая письма, которые появятся позже.

-- Отметка «в Telegram уже отправлено». Письмо возвращается в очередь при неудачной
-- отправке (до шести раз), и без этой отметки каждый повтор слал бы в чат дубль.
ALTER TABLE mail_outbox ADD COLUMN tg_sent_at TIMESTAMPTZ NULL;
