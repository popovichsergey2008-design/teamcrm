-- Порядок досок и «основные» доски компании.
--
-- Список проектов рос как придётся: сначала по дате создания, а импорт из YouGile и
-- Битрикса добавлял туда десятки чужих досок. Свои рабочие доски тонули среди них,
-- и найти нужную можно было только глазами по всему списку.
--
-- Два поля решают это вместе:
--   is_default — «основная доска компании». Такие всегда идут первыми, что бы ни
--   натворил очередной импорт.
--   sort_order — порядок внутри группы, который задают перетаскиванием. Меньше —
--   выше. У новых и импортированных проектов он нулевой, поэтому без ручной
--   расстановки список остаётся прежним (по дате создания, новые сверху).
--
-- Порядок общий для компании, а не личный: доски — общая рабочая поверхность, и
-- «у меня по-другому» здесь только мешает договариваться.
ALTER TABLE projects
    ADD COLUMN is_default BOOLEAN NOT NULL DEFAULT FALSE,
    ADD COLUMN sort_order INT NOT NULL DEFAULT 0;

CREATE INDEX idx_projects_order ON projects (tenant_id, is_default DESC, sort_order);
