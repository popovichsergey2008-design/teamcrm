/**
 * Разбор введённого списка почт (ТЗ-11, разд. 25).
 *
 * Отдельным файлом, а не внутри окна: это единственная часть приглашений, которую можно
 * проверить без браузера, — и та, где легче всего ошибиться. Человек вставляет что
 * угодно: список через запятую, столбец из таблицы, строки вида «Пётр <petr@c.ru>».
 * Заставлять его приводить это к «правильному» виду руками — верный способ получить
 * приглашение одному вместо пятерых.
 */

/** Всё, что похоже на адрес; повторы и регистр — это один и тот же человек. */
export function parseEmails(text: string): string[] {
  const found = String(text ?? '').match(/[^\s<>,;"]+@[^\s<>,;"]+\.[a-zа-я]{2,}/gi) ?? [];
  return [...new Set(found.map((e) => e.trim().toLowerCase()))];
}
