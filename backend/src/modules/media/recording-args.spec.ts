import { ffmpegArgs } from './recording.service';

/**
 * Запись созвона: короткий разговор должен сохраниться так же, как длинный.
 *
 * Живой случай, из-за которого этот тест появился: гостевой созвон на полминуты дал
 * две дорожки по НУЛЮ байт, и встреча не создалась вовсе — ни стенограммы, ни задач.
 * ffmpeg исправно принимал звук, но держал его в буфере: на диск он попадает либо при
 * переполнении, либо при корректном завершении. Корректного не случается — после ухода
 * человека поток обрывается, ffmpeg спит на приёме и SIGINT не слышит, его добивают.
 * Часовая планёрка это переживала (буфер переполнялся сам), получасовой разговор с
 * клиентом — уже нет.
 */
describe('Аргументы записи дорожки', () => {
  const args = ffmpegArgs('/tmp/rec/1.sdp', '/tmp/rec/1.ogg');

  it('сбрасывает на диск немедленно — иначе короткий созвон сохраняется нулём байт', () => {
    const i = args.indexOf('-flush_packets');
    expect(i).toBeGreaterThan(-1);
    expect(args[i + 1]).toBe('1');
  });

  it('пишет ogg без перекодирования: Opus и так родной формат для распознавания', () => {
    expect(args).toEqual(expect.arrayContaining(['-acodec', 'copy', '-f', 'ogg']));
    expect(args[args.length - 1]).toBe('/tmp/rec/1.ogg');
  });

  it('читает поток по SDP и не пускает ffmpeg в чужие протоколы', () => {
    const i = args.indexOf('-protocol_whitelist');
    expect(args[i + 1]).toBe('file,udp,rtp');
    expect(args[args.indexOf('-i') + 1]).toBe('/tmp/rec/1.sdp');
  });
});
