import { nextWednesday } from './deadline-shift';

/**
 * Календарь ошибается молча, поэтому «следующая среда» проверяется числами, а не
 * глазами: ошибка в один день замечается через неделю, когда срок уже прошёл.
 */
describe('«Сделал» — перенос срока на следующую среду 17:00', () => {
  const MSK = 'Europe/Moscow';
  /** Дата и время в Москве человеческой строкой: сравнивать UTC-метки невозможно. */
  const msk = (d: Date) => d.toLocaleString('ru-RU', { timeZone: MSK, weekday: 'long', hour: '2-digit', minute: '2-digit', day: '2-digit', month: '2-digit' });

  it('во вторник — ближайшая среда', () => {
    // вторник, 15 сентября 2026, 10:00 МСК
    expect(msk(nextWednesday(new Date('2026-09-15T07:00:00Z'), MSK))).toBe('среда, 16.09, 17:00');
  });

  it('в среду утром — СЛЕДУЮЩАЯ среда, а не сегодняшний вечер', () => {
    expect(msk(nextWednesday(new Date('2026-09-16T07:00:00Z'), MSK))).toBe('среда, 23.09, 17:00');
  });

  it('в среду после 17:00 — тоже следующая', () => {
    expect(msk(nextWednesday(new Date('2026-09-16T19:00:00Z'), MSK))).toBe('среда, 23.09, 17:00');
  });

  it('в воскресенье — ближайшая среда той же недели', () => {
    expect(msk(nextWednesday(new Date('2026-09-20T21:00:00Z'), MSK))).toBe('среда, 23.09, 17:00');
  });

  it('пояс человека, а не сервера: в Красноярске своя среда', () => {
    // среда 00:30 в Красноярске — это ещё вторник 21:30 по Москве
    const at = new Date('2026-09-15T17:30:00Z');
    expect(msk(nextWednesday(at, 'Asia/Krasnoyarsk'))).toBe('среда, 23.09, 13:00');
  });
});
