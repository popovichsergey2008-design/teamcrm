/**
 * База «вопрос — ответ» для первой линии Отдела заботы (#4837).
 *
 * Заказчик ведёт одну таблицу вопросов и ответов (лист «Приложение» — для app.qevo.one,
 * «Сайт» — для бота на qevo.one; собирает их scripts/qa-base/build_qa.py). Частые
 * вопросы — «как поставить задачу голосом», «есть ли подзадачи» — не нужно гонять
 * через модель: ответ уже написан и проверен людьми, он приходит мгновенно, не тратит
 * токены и не «плавает» от раза к разу.
 *
 * Поэтому здесь чистая функция без ИИ: нормализуем текст, режем слова до основы и
 * сравниваем с вопросом и его «другими формулировками». Отвечаем, только когда
 * совпадение уверенное и однозначное, — иначе null, и вопрос идёт к модели, как раньше.
 * Ошибиться в сторону «не узнал» дёшево (ответит модель), в сторону «узнал не то» —
 * дорого: человек получает уверенный ответ не на свой вопрос.
 *
 * ГРАБЛИ, на которых мы уже обжигались: `\b` и `\w` в JS не видят кириллицу, поэтому
 * буквы перечисляем явно ([a-zа-я0-9]), а не классами символов.
 */

export interface QaEntry {
  id: string;
  segment: string;
  question: string;
  aliases: string[];
  answer: string;
  bucket: string;
  /** Корзина C без ответа команды: честно говорим «уточню» и зовём человека. */
  handoff: boolean;
}

export interface QaHit {
  entry: QaEntry;
  score: number;
}

/** Порог уверенности (коэффициент Дайса по основам слов). Подобран на самой базе: см. spec. */
const MIN_SCORE = 0.7;
/** На сколько лучший ответ должен обгонять следующий, чтобы считаться однозначным. */
const MIN_MARGIN = 0.1;
/*
  Длинное сообщение — уже не вопрос из базы, а рассказ о своей ситуации.

  «У меня на доске пропала колонка после того, как коллега…» может задеть пару слов
  частого вопроса, но ответ «шаблоном» на рассказ звучит как «вас не прочитали».
  Такое пусть разбирает модель с контекстом экрана.
*/
const MAX_TOKENS = 12;
/*
  Сколько значимых слов сообщения должно найтись в формулировке.

  Лишнее слово в сообщении — обычно и есть суть вопроса: «как поставить СРОК задаче»
  делит два слова с «поставленные задачи», но спрашивает о сроке. Поэтому оцениваем не
  только общую похожесть, но и то, что из сказанного человеком мы покрыли.
*/
const MIN_COVERAGE = 0.75;

/*
  Слова, которые ничего не говорят о сути вопроса.

  Без них «а можно ли у вас поставить задачу голосом» и «как поставить задачу голосом»
  сводятся к одному и тому же. Название продукта — тоже сюда: оно есть почти в каждом
  вопросе и только размывает сравнение.
*/
const STOP = new Set([
  'а', 'и', 'в', 'во', 'на', 'по', 'с', 'со', 'к', 'ко', 'у', 'о', 'об', 'от', 'до', 'из', 'за',
  'для', 'при', 'без', 'не', 'ни', 'но', 'же', 'бы', 'ли', 'то', 'или', 'если', 'чтобы', 'как',
  'что', 'где', 'когда', 'почему', 'зачем', 'какой', 'какая', 'какие', 'какое', 'каких', 'который',
  'которая', 'которые', 'это', 'этот', 'эта', 'эти', 'тот', 'та', 'те', 'я', 'мы', 'вы', 'он', 'она',
  'они', 'мне', 'меня', 'мой', 'моя', 'мои', 'моих', 'нам', 'нас', 'наш', 'наша', 'наши', 'вас', 'вам',
  'ваш', 'ваша', 'ваши', 'его', 'ее', 'их', 'есть', 'там', 'тут', 'здесь', 'сейчас', 'уже', 'еще',
  'так', 'такой', 'такое', 'очень', 'просто', 'вообще', 'пожалуйста', 'подскажите', 'скажите',
  'можно', 'могу', 'можем', 'нужно', 'надо', 'будет', 'был', 'была', 'быть', 'все', 'всё', 'весь',
  'делать', 'сделать', 'хочу', 'хотим', 'ну', 'вот', 'привет', 'здравствуйте', 'спасибо',
  'qevo', 'кево', 'ково',
]);

/*
  Окончания — грубо, но предсказуемо.

  Полноценный морфологический разбор здесь избыточен: вопросы короткие, и после
  отсечения окончания основа режется до пяти букв — «задачу», «задачи», «задачей»
  сходятся в «задач», «перенести» и «перенос» — в «перен».
*/
const ENDINGS = [
  'иями', 'ями', 'ами', 'ого', 'его', 'ому', 'ему', 'ыми', 'ими', 'ость', 'ости', 'ться', 'тся',
  'ать', 'ять', 'ить', 'еть', 'уть', 'ешь', 'ете', 'ишь', 'ите', 'ует', 'уют', 'ают', 'яют', 'ает',
  'яет', 'ила', 'ило', 'или', 'ала', 'али', 'ыла', 'ыли', 'ией', 'иям', 'ием', 'иях', 'ах', 'ях',
  'ам', 'ям', 'ом', 'ем', 'ой', 'ей', 'ий', 'ый', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие', 'ую', 'юю',
  'ов', 'ев', 'ия', 'ья', 'ь', 'а', 'я', 'о', 'е', 'ы', 'и', 'у', 'ю', 'й',
];
const STEM_LEN = 5;

/** Нижний регистр, ё → е, всё кроме букв и цифр — в пробел. */
export function normalizeQa(text: string): string {
  return String(text ?? '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .replace(/[^a-zа-я0-9]+/g, ' ')
    .trim();
}

/** Основа слова: без окончания и не длиннее пяти букв. Короткие («ии», «1с», «api») — как есть. */
export function stemQa(word: string): string {
  if (word.length <= 3 || !/[а-я]/.test(word)) return word;
  for (const end of ENDINGS) {
    if (word.endsWith(end) && word.length - end.length >= 3) {
      word = word.slice(0, -end.length);
      break;
    }
  }
  return word.slice(0, STEM_LEN);
}

/** Основы значимых слов фразы, без повторов. */
export function tokensQa(text: string): string[] {
  const out = new Set<string>();
  for (const w of normalizeQa(text).split(' ')) {
    if (w && !STOP.has(w)) out.add(stemQa(w));
  }
  return [...out];
}

interface Phrase {
  norm: string;
  tokens: Set<string>;
  negative: boolean;
}

/*
  «Не» меняет вопрос на противоположный.

  «Вложения не открываются в задаче» и «вложенные задачи» после обрезки основ делят
  оба слова, но первое — жалоба на поломку, второе — вопрос о функции. Отрицание
  выбрасывается вместе со служебными словами, поэтому смотрим на него отдельно: у
  сообщения и формулировки оно должно совпадать.
*/
function isNegative(norm: string): boolean {
  return /(^| )(не|нет|ни|нельзя)( |$)/.test(norm);
}
interface Indexed {
  entry: QaEntry;
  phrases: Phrase[];
}

// Разбор базы — один раз на массив: база статична, а вызов идёт на каждое сообщение.
const cache = new WeakMap<readonly QaEntry[], Indexed[]>();
function indexOf(entries: readonly QaEntry[]): Indexed[] {
  let idx = cache.get(entries);
  if (!idx) {
    idx = entries.map((entry) => ({
      entry,
      phrases: [entry.question, ...(entry.aliases ?? [])]
        .map((p) => {
          const norm = normalizeQa(p);
          return { norm, tokens: new Set(tokensQa(p)), negative: isNegative(norm) };
        })
        .filter((p) => p.norm),
    }));
    cache.set(entries, idx);
  }
  return idx;
}

/** Похожесть сообщения на одну формулировку: 1 — дословно, дальше Дайс по основам. */
function similarity(norm: string, q: Set<string>, p: Phrase): number {
  if (norm === p.norm) return 1;
  if (!q.size || !p.tokens.size || isNegative(norm) !== p.negative) return 0;
  let common = 0;
  for (const t of q) if (p.tokens.has(t)) common++;
  /*
    Одно общее слово — не совпадение, а случайность: «подзадачи не создаются» и
    «есть ли подзадачи?» делят ровно одно слово, но спрашивают о разном. Исключение —
    когда и вопрос, и формулировка состоят из одного значимого слова.
  */
  if (common < 2 && !(common === 1 && q.size === 1 && p.tokens.size === 1)) return 0;
  if (common / q.size < MIN_COVERAGE) return 0;
  return (2 * common) / (q.size + p.tokens.size);
}

/**
 * Лучший ответ из базы — или null, если уверенного и однозначного совпадения нет.
 */
export function matchQa(text: string, entries: readonly QaEntry[]): QaHit | null {
  const norm = normalizeQa(text);
  if (!norm) return null;
  const q = new Set(tokensQa(text));
  if (q.size > MAX_TOKENS) return null;

  const idx = indexOf(entries);
  // Вопрос слово в слово как в базе — ответ однозначный, даже если такая же фраза
  // встречается у другого вопроса среди «других формулировок».
  const exact = idx.find((it) => it.phrases[0]?.norm === norm);
  if (exact) return { entry: exact.entry, score: 1 };

  let best: QaHit | null = null;
  let second = 0;
  for (const it of idx) {
    let score = 0;
    for (const p of it.phrases) score = Math.max(score, similarity(norm, q, p));
    if (!score) continue;
    if (!best || score > best.score) {
      second = best?.score ?? 0;
      best = { entry: it.entry, score };
    } else if (score > second) {
      second = score;
    }
  }
  if (!best || best.score < MIN_SCORE) return null;
  /*
    Два почти одинаково похожих ответа — значит, мы не поняли, о чём вопрос.

    Касается и дословных совпадений: одна и та же короткая формулировка («чек-лист»,
    «пропала задача») записана в базе у нескольких вопросов — выбрать первый попавшийся
    значит угадывать.
  */
  if (best.score - second < MIN_MARGIN) return null;
  return best;
}
