/**
 * Роль процесса API (нагрузка 05.11: один процесс Node упирался в одно ядро при ~300
 * одновременно работающих, а остальные ядра сервера простаивали).
 *
 * - `main` (по умолчанию, ровно один): всё, как раньше, — фоновые планировщики (напоминания,
 *   сводки, письма, повторы задач…), созвоны (mediasoup живёт в памяти процесса), сокеты.
 * - `web` (сколько угодно): только запросы API. Планировщики здесь не запускаются — иначе
 *   каждое напоминание ушло бы столько раз, сколько процессов. Созвоны, гостевые ссылки
 *   и консоль поддержки nginx отправляет в main.
 *
 * Не задано — main: один процесс ведёт себя ровно как до разделения (dev, тесты, старт).
 */
export type ApiRole = 'main' | 'web';

export const API_ROLE: ApiRole = process.env.API_ROLE === 'web' ? 'web' : 'main';

/** Запускать ли фоновую работу (таймеры, планировщики, звонковый сервер) в этом процессе. */
export function runsBackground(): boolean {
  return API_ROLE === 'main';
}
