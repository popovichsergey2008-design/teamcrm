-- Слой 8 ТЗ-3: внешний чат.
--
-- Клиента и подрядчика зовут в разговор по ссылке — без учётной записи, без доступа
-- к задачам, проектам и остальной переписке. Механика та же, что у гостевых созвонов:
-- ссылка знает свой разговор, в базе от неё только отпечаток.
--
-- Разделение внутреннего и клиентского — принципиальное. «Клиент опять поменял
-- требования» должно быть сказано в ВНУТРЕННЕМ чате проекта, и случайно уехать
-- клиенту оно не может, потому что это разные чаты, а не один с фильтром.
ALTER TABLE chats ADD COLUMN is_external BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE chats ADD COLUMN client_id BIGINT NULL REFERENCES clients(id) ON DELETE SET NULL;

-- Имя внешнего собеседника прямо в сообщении.
--
-- У гостя нет строки в users, а «сообщение без автора» у нас означает системную
-- строку. Имя хранится с сообщением: гость представился при входе, и через месяц
-- в переписке должно быть видно, кто именно это писал.
ALTER TABLE chat_messages ADD COLUMN guest_name VARCHAR(60) NULL;

CREATE INDEX idx_chats_external ON chats (tenant_id) WHERE is_external = TRUE;
