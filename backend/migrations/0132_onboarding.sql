-- Онбординг владельца (ТЗ-11): состояние пути и настройки компании.
--
-- ЧТО ЗДЕСЬ НЕ ХРАНИТСЯ И ПОЧЕМУ. В исходном ТЗ у каждого шага своя отметка
-- «выполнен». Мы так не делаем: шаг считается пройденным по ФАКТУ — есть проект, есть
-- задача, заведён отдел. Отметки рассинхронизируются с жизнью на первой же неделе
-- (владелец создал проект мимо мастера, а галочка не встала), и человек видит
-- незавершённый онбординг поверх работающей компании.
--
-- Поэтому храним только то, чего по данным не узнать: что человек решил пропустить,
-- убрал ли он подсказку и когда путь был признан завершённым.
CREATE TABLE IF NOT EXISTS tenant_onboarding (
    tenant_id     BIGINT      PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
    -- Кто проходит путь: владелец, создавший пространство.
    owner_user_id BIGINT      NULL REFERENCES users(id) ON DELETE SET NULL,
    -- Шаги, которые человек отложил кнопкой «Позже»: company | departments | team.
    skipped       TEXT[]      NOT NULL DEFAULT '{}',
    -- Единственный шаг, который по данным не увидеть: настройки компании можно было и
    -- не трогать — у пояса есть значение по умолчанию. Поэтому подтверждение отмечаем.
    company_confirmed_at TIMESTAMPTZ NULL,
    -- Подсказку свернули совсем. Открыть заново — из настроек.
    dismissed     BOOLEAN     NOT NULL DEFAULT FALSE,
    -- Путь пройден: проект и задача есть. Дальше подсказка не навязывается.
    completed_at  TIMESTAMPTZ NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Настройки компании — в самой организации, а не отдельной таблицей: это её свойства,
-- и join за ними ходить незачем.
--
-- Часовой пояс ОРГАНИЗАЦИИ нужен отдельно от пояса человека: по нему считаются сроки
-- задач без указания времени, рабочие часы, тихие часы и утренние сводки. Пока его не
-- было, всё это считалось по Москве, даже если компания работает во Владивостоке.
ALTER TABLE tenants
    ADD COLUMN IF NOT EXISTS timezone     VARCHAR(48) NOT NULL DEFAULT 'Europe/Moscow',
    -- Логотип: файл из общего хранилища, чтобы жил по тем же правилам доступа.
    ADD COLUMN IF NOT EXISTS logo_file_id BIGINT      NULL REFERENCES files(id) ON DELETE SET NULL,
    -- Отрасль: по ней предлагаются отделы при первой настройке (см. industries.ts).
    ADD COLUMN IF NOT EXISTS industry     VARCHAR(48) NULL;
