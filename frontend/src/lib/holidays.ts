/**
 * Нерабочие праздничные дни России.
 *
 * Здесь только то, что закреплено в статье 112 ТК и не меняется от года к году.
 * ПЕРЕНОСОВ ЗДЕСЬ НЕТ И НЕ БУДЕТ: их правительство утверждает отдельным постановлением
 * на каждый год, и зашитая таблица переносов молча устарела бы — а «молча устарел»
 * для производственного календаря означает встречу, назначенную на выходной.
 *
 * Поэтому кнопка в настройках подставляет фиксированные даты, а перенесённые дни
 * владелец добавляет руками, сверившись с постановлением.
 */

export interface Holiday {
  /** YYYY-MM-DD */
  date: string;
  name: string;
}

/** Месяц (1–12), день и название — как в статье 112 ТК РФ. */
