-- Завершение задачи с согласованием постановщика.
--
-- «Готово» от исполнителя и «принято» от постановщика — разные события, а до сих пор
-- это было одно: перенёс карточку в «Готово» — задача закрыта, и постановщик узнавал
-- об этом (если узнавал) из ленты. Теперь по умолчанию работа сдаётся на подтверждение:
-- исполнитель говорит «сделал», постановщик отвечает «принял» или «верни в работу».
--
-- По умолчанию ВКЛЮЧЕНО осознанно: это поведение, которое люди и так имитируют вручную
-- («напиши мне, когда закончишь»). Кому оно мешает — снимает галочку при создании.

ALTER TABLE tasks
    -- нужно ли подтверждение постановщика, чтобы задача считалась завершённой
    ADD COLUMN requires_approval BOOLEAN NOT NULL DEFAULT TRUE,
    -- none | pending: работа сдана и ждёт ответа постановщика
    ADD COLUMN approval_state VARCHAR(12) NOT NULL DEFAULT 'none',
    ADD COLUMN approval_requested_at TIMESTAMPTZ NULL,
    ADD COLUMN approval_requested_by BIGINT NULL REFERENCES users(id);

-- Задачи, ждущие подтверждения, ищут и постановщик в своём списке, и счётчик «требует
-- решения»: выборка идёт по состоянию, а не по колонке.
CREATE INDEX idx_tasks_approval_pending
    ON tasks (tenant_id, created_by)
    WHERE approval_state = 'pending';

-- Старым задачам согласование не включаем: они жили по другим правилам, и внезапно
-- «незавершённые» закрытые задачи сломали бы и отчёты, и доверие к системе.
UPDATE tasks SET requires_approval = FALSE WHERE closed_at IS NOT NULL;
