/**
 * Выделенный кусок сообщения.
 *
 * Нужен в двух местах, и оба — просьбы заказчика: «копируется всё сообщение, надо
 * как в телеге — скопировать выделенное» и «процитировать именно кусок выделенного
 * сообщения».
 *
 * Тонкость, из-за которой это вынесено отдельно: выделение надо снять В МОМЕНТ
 * вызова меню. Пока человек ведёт мышь к пункту, любой щелчок выделение сбрасывает —
 * и «копировать выделенное» скопировало бы пустоту.
 */

/** Сколько знаков берём в цитату: дальше это уже не цитата, а пересказ. */
const MAX = 600;

/**
 * Что выделено внутри этого узла. Пусто — если выделения нет или оно снаружи:
 * цитировать чужую реплику, водя мышью по соседней, нельзя.
 */
export function selectionIn(node: Element | null | undefined): string {
  if (!node) return '';
  const sel = window.getSelection();
  if (!sel || sel.isCollapsed || sel.rangeCount === 0) return '';
  const range = sel.getRangeAt(0);
  // Выделение должно и начинаться, и заканчиваться внутри сообщения.
  if (!node.contains(range.startContainer) || !node.contains(range.endContainer)) return '';
  return sel.toString().trim().slice(0, MAX);
}
