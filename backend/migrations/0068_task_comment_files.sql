-- Файл прямо в сообщении и цитата выделенного куска.
--
-- Файлы по задаче жили отдельной вкладкой: чтобы показать скриншот в обсуждении,
-- надо было уйти во «Файлы», загрузить, вернуться и написать «см. вложение». Теперь
-- файл прикладывается к самому сообщению — и остаётся в общем списке вложений, чтобы
-- вкладка «Файлы» по-прежнему отвечала на вопрос «что вообще есть по задаче».
ALTER TABLE task_comments ADD COLUMN file_id BIGINT NULL REFERENCES files(id);

-- Ответ на ЧАСТЬ сообщения, а не на всё целиком.
--
-- В длинном сообщении обсуждают обычно один абзац. Цитата целиком («да, согласен»
-- под простынёй текста) не отвечает на вопрос, с чем именно согласны. Здесь лежит
-- выделенный человеком кусок; пусто — цитируется начало сообщения, как раньше.
ALTER TABLE task_comments ADD COLUMN reply_excerpt TEXT NULL;
