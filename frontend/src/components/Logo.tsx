/**
 * Знак ANTHILL.TEAM.
 *
 * Настоящий фирменный знак картинкой, а не векторной реконструкцией.
 *
 * Раньше здесь была нарисованная нами «похожая» фигура — вынужденно, пока не было
 * оригинала: исходник это неон на чёрном, и на белом фоне он превращался в тёмный
 * прямоугольник. Оригинал есть, и заказчик просит именно его — значит, показываем
 * его, а не свою версию: логотип не тот случай, где «почти так же» годится.
 *
 * Тёмная подложка не прячется, а оформляется: знак живёт скруглённой плиткой, как
 * иконка приложения. В светлой теме это выглядит намеренно, а не как «картинку забыли
 * обработать» — и ровно так же он выглядит на вкладке браузера и на телефоне.
 *
 * Размеры: одна картинка 512×512 на всё. Мельче 24 пикселей знак не ставим — в нём
 * полтора десятка тонких линий, и на такой шкале от них остаётся свечение.
 */
export function Logo({ size = 32, withWord = false }: { size?: number; withWord?: boolean }) {
  const mark = (
    <img
      className="logo-mark"
      src="/logo-mark.png"
      width={size}
      height={size}
      alt=""
      aria-hidden="true"
      draggable={false}
    />
  );

  if (!withWord) return mark;

  return (
    <span className="logo">
      {mark}
      {/* Слово набрано текстом, а не взято из картинки: оно ищется поиском, читается
          скринридером и не мылится на любом экране. */}
      <span className="logo-word">ANTHILL<span className="logo-dot">.</span>TEAM</span>
    </span>
  );
}
