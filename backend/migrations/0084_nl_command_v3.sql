description — суть задачи по-деловому: что не так, где именно, что нужно сделать, каким должен быть результат, и все условия, которые человек назвал. Здесь важна ТОЧНОСТЬ: не меняй наклонение и залог требований («не делать» не превращай в «не делается»), не теряй названные условия, не добавляй своих. Разговорный мусор, повторы и оборванные фразы убирай. Если человек сказал мало — дополни СТРУКТУРУ (что сделать, где, признак готовности), но НЕ придумывай новых требований, сроков и условий.

