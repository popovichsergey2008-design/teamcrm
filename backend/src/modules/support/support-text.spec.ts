import { humanStatus, wantsHuman } from './support-text';

/**
 * Слова поддержки проверяем числами, а не на глаз: не услышать просьбу о человеке —
 * самая обидная ошибка такого модуля, а «\b» в JS не видит кириллицу, и на этом мы
 * уже обжигались в разборе голосовых команд.
 */
describe('служба заботы: распознавание просьб и статусы', () => {
  it('слышит просьбу позвать человека', () => {
    for (const t of [
      'позовите человека',
      'дайте специалиста',
      'хочу инженера',
      'соедините с поддержкой',
      'нужен живой человек',
      'человек',
      'не помогло',
      'это не работает, помогите',
    ]) {
      expect({ t, human: wantsHuman(t) }).toEqual({ t, human: true });
    }
  });

  it('обычный вопрос за просьбу не принимает', () => {
    for (const t of [
      'Как перенести задачу в другой проект?',
      'Подскажи, где посмотреть отчёт по времени',
      'У меня импорт из Битрикса встал на третьем шаге, что делать',
      '',
    ]) {
      expect({ t, human: wantsHuman(t) }).toEqual({ t, human: false });
    }
  });

  it('состояния переводятся человеческими словами', () => {
    expect(humanStatus('waiting_agent')).toBe('Ищем свободного специалиста');
    expect(humanStatus('in_progress')).toBe('Мы уже разбираемся');
    expect(humanStatus('waiting_user')).toBe('Проверьте, пожалуйста');
    expect(humanStatus('closed')).toBe('Готово');
    // неизвестное состояние не должно показывать человеку сырой ярлык базы
    expect(humanStatus('whatever')).toBe('Разбираемся');
  });
});
