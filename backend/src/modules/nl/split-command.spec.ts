import { splitCommand, stripMarker } from './split-command';

/**
 * Деление команды правилами (ТЗ-10, этап 1). Главное правило: НЕ выдумывать.
 * Лучше одна честная задача, чем три нарезанных по точкам.
 */
describe('splitCommand', () => {
  it('делит по словам-разделителям', () => {
    const parts = splitCommand(
      'Проверить форму регистрации до пятницы. Вторая задача: написать текст для лендинга. Третья задача — обновить документацию по API.',
    );
    expect(parts).toHaveLength(3);
    expect(parts[0]).toContain('форму регистрации');
    expect(parts[1]).toBe('написать текст для лендинга');
    expect(parts[2]).toBe('обновить документацию по API');
  });

  it('делит нумерованный список строками', () => {
    const parts = splitCommand('1. Исправить API авторизации\n2) Переделать карточку задачи\n3. Подготовить текст для лендинга');
    expect(parts).toEqual(['Исправить API авторизации', 'Переделать карточку задачи', 'Подготовить текст для лендинга']);
  });

  it('делит по «также» и «затем»', () => {
    const parts = splitCommand('Поставь Глебу исправить форму входа. Также нужно обновить справку по оплате.');
    expect(parts).toHaveLength(2);
    expect(parts[1]).toContain('обновить справку');
  });

  it('НЕ делит связный текст по точкам — это одна задача с пояснением', () => {
    const one = splitCommand('Проверить форму регистрации. Она не работает на телефоне, кнопка уезжает под футер.');
    expect(one).toHaveLength(1);
  });

  it('ловит порядковое слово с двоеточием без слова «задача»', () => {
    const parts = splitCommand('Написать текст для лендинга. Третья: обновить документацию по API.');
    expect(parts).toHaveLength(2);
    expect(parts[1]).toBe('обновить документацию по API');
  });

  it('«Первая попытка не удалась» — не разделитель, а продолжение мысли', () => {
    expect(splitCommand('Починить выгрузку отчётов. Первая попытка не удалась, падает на большом файле.')).toHaveLength(1);
  });

  it('короткую команду отдаёт как есть', () => {
    expect(splitCommand('Позвонить Сергею')).toEqual(['Позвонить Сергею']);
    expect(splitCommand('  ')).toEqual([]);
  });

  it('не плодит обрывки: «и всё» к задаче не относится', () => {
    const parts = splitCommand('Исправить форму регистрации до пятницы. Также обновить документацию. И всё.');
    expect(parts).toHaveLength(2);
    expect(parts.every((p) => p.length > 12)).toBe(true);
  });

  it('держит предел в десять поручений', () => {
    const many = Array.from({ length: 15 }, (_, i) => `${i + 1}. Задача номер ${i + 1} с описанием`).join('\n');
    expect(splitCommand(many)).toHaveLength(10);
  });

  it('stripMarker убирает номер и «вторая задача»', () => {
    expect(stripMarker('2) Обновить документацию')).toBe('Обновить документацию');
    expect(stripMarker('Вторая задача: написать текст')).toBe('написать текст');
    expect(stripMarker('Обычный заголовок')).toBe('Обычный заголовок');
  });
});
