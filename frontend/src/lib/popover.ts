/**
 * Куда раскрыть всплывающее меню сообщения.
 *
 * Набор реакций и меню «ещё» жили ВНУТРИ ленты, у которой своя прокрутка, и всегда
 * раскрывались вверх. В ветке обсуждения сообщений мало, и первое из них стоит у
 * самого верха панели: всплывашка уезжала за границу прокручиваемой области и
 * обрезалась целиком. Со стороны это выглядело как «в тредах нельзя ни смайлы
 * поставить, ни удалить, ни задачу создать» — кнопка нажимается, а не происходит
 * ничего.
 *
 * Поэтому место считаем сами, координатами окна: сверху не помещается — раскрываем
 * вниз; у правого края — прижимаем, чтобы меню не уехало за экран.
 *
 * Отдельным файлом, а не внутри страницы чатов: это единственная часть всей истории,
 * которую можно проверить без браузера, — и она же единственная, где легко ошибиться.
 */

/** Прямоугольник кнопки в координатах окна (то, что отдаёт getBoundingClientRect). */
export interface AnchorRect { left: number; top: number; bottom: number }

export interface PopoverPlace {
  /** Левый край всплывашки в координатах окна. */
  x: number;
  /** Точка привязки по вертикали: при `up` это НИЖНИЙ край (сдвигается translateY(-100%)). */
  y: number;
  /** Раскрываемся вверх (есть место над кнопкой) или вниз. */
  up: boolean;
}

/** Зазор между кнопкой и всплывашкой, чтобы они не слипались. */
const GAP = 6;
/** Минимальный отступ от краёв окна: впритык к краю читается как обрезанное. */
const EDGE = 8;

export function placePopover(
  rect: AnchorRect,
  height: number,
  viewportWidth: number,
  width = 232,
): PopoverPlace {
  // Места сверху должно хватить на саму всплывашку и на зазор — иначе вниз.
  const up = rect.top > height + GAP + EDGE;
  return {
    x: Math.max(EDGE, Math.min(rect.left, viewportWidth - width - EDGE)),
    y: up ? rect.top - GAP : rect.bottom + GAP,
    up,
  };
}
