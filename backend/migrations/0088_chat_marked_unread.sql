-- «Пометить как непрочитанное» — как в Telegram.
--
-- Человек прочитал сообщение на бегу и хочет вернуться к нему позже: помечает
-- чат непрочитанным, и он снова светится в списке. Это ЛИЧНАЯ пометка: ни
-- собеседник, ни его галочки «прочитано» от неё не меняются — он-то видел, что
-- прочитали.
--
-- Поэтому не двигаем last_read_at назад (это и врало бы собеседнику, и путало бы
-- счётчик), а держим отдельный флаг. Снимается он тем же, чем ставится отметка
-- о прочтении: открыл чат — пометка ушла.
ALTER TABLE chat_members
    ADD COLUMN marked_unread BOOLEAN NOT NULL DEFAULT false;
