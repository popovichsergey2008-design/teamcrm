import { dative, firstName, genitive, instrumental, plural } from './ru-names';

describe('склонение имён (#1525)', () => {
  const table: [string, string, string, string][] = [
    ['Сергей Попович', 'Сергея', 'Сергею', 'Сергеем'],
    ['Константин', 'Константина', 'Константину', 'Константином'],
    ['Глеб', 'Глеба', 'Глебу', 'Глебом'],
    ['Борис', 'Бориса', 'Борису', 'Борисом'],
    ['Игорь', 'Игоря', 'Игорю', 'Игорем'],
    ['Евгений', 'Евгения', 'Евгению', 'Евгением'],
    ['Анна', 'Анны', 'Анне', 'Анной'],
    ['Ольга', 'Ольги', 'Ольге', 'Ольгой'],
    ['Саша', 'Саши', 'Саше', 'Сашей'],
    ['Никита', 'Никиты', 'Никите', 'Никитой'],
    ['Мария', 'Марии', 'Марии', 'Марией'],
    ['Дарья', 'Дарьи', 'Дарье', 'Дарьей'],
    ['Илья', 'Ильи', 'Илье', 'Ильёй'],
    ['Павел', 'Павла', 'Павлу', 'Павлом'],
    ['Любовь', 'Любови', 'Любови', 'Любовью'],
    ['Нико', 'Нико', 'Нико', 'Нико'],
    ['John Smith', 'John', 'John', 'John'],
  ];
  it.each(table)('%s', (full, gen, dat, ins) => {
    expect(genitive(full)).toBe(gen);
    expect(dative(full)).toBe(dat);
    expect(instrumental(full)).toBe(ins);
  });

  it('первое слово и пустое', () => {
    expect(firstName('  Анна   Ким ')).toBe('Анна');
    expect(genitive(null)).toBe('');
  });

  it('число', () => {
    expect([1, 2, 5, 11, 12, 21, 22, 25, 111].map((n) => plural(n, 'задача', 'задачи', 'задач')))
      .toEqual(['задача', 'задачи', 'задач', 'задач', 'задач', 'задача', 'задачи', 'задач', 'задач']);
  });
});
