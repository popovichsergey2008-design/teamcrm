/**
 * Внутреннее состояние → что видит человек (ТЗ-8, разд. 20).
 *
 * Внутри нам нужны сухие ярлыки для очереди и отчётов, а человеку — понятная фраза.
 * Показывать ему `waiting_agent` значит разговаривать на языке своей базы данных.
 */
const HUMAN: Record<string, string> = {
  new: 'Разбираемся',
  ai: 'Помощник разбирается',
  waiting_agent: 'Ищем свободного специалиста',
  in_progress: 'Мы уже разбираемся',
  engineer_escalated: 'Разбираются инженеры',
  fix_in_progress: 'Готовим исправление',
  waiting_reply: 'Ждём вашего ответа',
  waiting_user: 'Проверьте, пожалуйста',
  resolved: 'Готово',
  closed: 'Готово',
};

export function humanStatus(status: string): string {
  return HUMAN[status] ?? 'Разбираемся';
}

/**
 * Просьба позвать человека.
 *
 * Ловим не «команду», а живую речь: «позови специалиста», «дайте человека»,
 * «не помогло», «хочу инженера». Ошибиться в эту сторону не страшно — человек и
 * так может быть позван кнопкой; страшно НЕ услышать просьбу и продолжить отвечать
 * роботом (разд. 9).
 *
 * ГРАБЛИ, на которых мы уже обжигались: `\b` и `\w` в JS не видят кириллицу, поэтому
 * границы слов ищем пробелами и знаками препинания, а не классами символов.
 */
const HUMAN_ASKS = [
  'человек', 'человека', 'людей', 'живого', 'живой',
  'специалист', 'специалиста', 'инженер', 'инженера',
  'оператор', 'оператора', 'поддержк', 'менеджер',
];
/*
  «Не помогло» — та же просьба о человеке, только другими словами.

  Короткие обрывки вроде «не то» сюда не берём: они живут внутри обычных слов
  («не только», «не тот файл») и превратили бы каждую вторую реплику в вызов
  специалиста.
*/
const FAILED = ['не помогл', 'не работает', 'не получилось', 'не помогает', 'бесполезно'];

export function wantsHuman(text: string): boolean {
  const t = String(text ?? '').toLowerCase();
  if (!t.trim()) return false;
  // «позови/дай/соедини/нужен … человек» — и просто «человек» отдельным словом
  const asksPerson = HUMAN_ASKS.some((w) => t.includes(w));
  const asksVerb = /(позов|позвать|дай|дайте|соедин|нужен|нужна|хочу|свяжите|переключ)/.test(t);
  if (asksPerson && (asksVerb || t.trim().split(/\s+/).length <= 3)) return true;
  // «не помогло» после ответа помощника — та же просьба, только другими словами
  return FAILED.some((w) => t.includes(w)) && t.length < 120;
}
