/**
 * Чем проверяющий может дополнить материалы.
 *
 * Список закрытый и короткий: это не свободные инструменты, а три способа достать
 * ровно то, что мы и так умеем отдавать. Открывать сюда произвольные запросы к
 * данным нельзя — проверка читает чужие задачи под правами того, кто её нажал.
 */
export const EVIDENCE_TOOLS = ['переписка', 'файл', 'база_знаний'] as const;
export type EvidenceTool = (typeof EVIDENCE_TOOLS)[number];
export interface EvidenceNeed { tool: EvidenceTool; arg: string }

/** Больше трёх дозапросов за заход — это уже не проверка, а перебор материалов. */
const MAX_NEEDS = 3;

/**
 * Разбор дозапроса.
 *
 * Возвращает пустой список на всё, что не похоже на просьбу о материалах: тогда
 * ответ разбирается как обычный отчёт. Неизвестные названия инструментов молча
 * отбрасываем — выдуманный инструмент не должен останавливать проверку.
 */
export function parseNeeds(raw: string): EvidenceNeed[] {
  const start = raw.indexOf('{');
  const end = raw.lastIndexOf('}');
  if (start < 0 || end <= start) return [];
  let obj: Record<string, unknown>;
  try { obj = JSON.parse(raw.slice(start, end + 1)); } catch { return []; }
  const rows = obj.need ?? (obj as Record<string, unknown>).needs;
  if (!Array.isArray(rows)) return [];
  const out: EvidenceNeed[] = [];
  for (const r of rows as Record<string, unknown>[]) {
    const tool = String(r?.['чем'] ?? r?.tool ?? '').trim() as EvidenceTool;
    if (!EVIDENCE_TOOLS.includes(tool)) continue;
    const arg = String(r?.['что'] ?? r?.arg ?? '').trim().slice(0, 200);
    // «файл» без имени и поиск без запроса выполнить нечем.
    if (tool !== 'переписка' && !arg) continue;
    if (!out.some((n) => n.tool === tool && n.arg === arg)) out.push({ tool, arg });
    if (out.length >= MAX_NEEDS) break;
  }
  return out;
}

/**
 * Статус пункта.
 *
 * `no_proof` появился после живой жалобы: проверяющий ставил «✗ не выполнено» всюду,
 * где просто не нашёл доказательства, и отчёт читался как обвинение исполнителя.
 * Разница принципиальная: «я не нашёл подтверждения» — не то же самое, что «этого нет».
 */
export type CheckStatus = 'ok' | 'no_proof' | 'no' | 'unclear';

export interface ReviewResult {
  verdict: 'done' | 'partial' | 'not_done' | 'cannot_check';
  summary: string;
  checked: { what: string; status: CheckStatus; evidence: string }[];
  missing: string[];
  askHuman: string[];
  confidence: number;
}

const VERDICT_TITLE: Record<ReviewResult['verdict'], string> = {
  done: 'Проверил: похоже, сделано',
  partial: 'Проверил: сделано не всё',
  not_done: 'Проверил: подтверждений выполнения нет',
  cannot_check: 'Проверить по материалам задачи не смог',
};

const MARK: Record<string, string> = { ok: '✓', no: '✗', no_proof: '?', unclear: '?' };

/** Что проверяющий вообще видел: без этого вывод выглядит взятым с потолка. */
export interface ReviewSources {
  messages: number;
  attachments: number;
  history: number;
  minutes: number;
  images: number;
  /** Сколько пунктов чек-листа отмечено исполнителем и сколько их всего. */
  checklistDone?: number;
  checklistTotal?: number;
  /** Что дозапросил сверх карточки — человеческими словами. */
  extra?: string[];
}

/**
 * Есть ли в задаче хоть какие-то следы работы.
 *
 * Отмеченный чек-лист сюда входит: его ставит исполнитель, и как доказательство
 * выполнения он слаб, но как признак того, что задачей занимались, — вполне.
 */
function hasTraces(s: ReviewSources): boolean {
  return !!(s.messages || s.attachments || s.history || s.minutes || s.checklistDone);
}

/**
 * Последнее слово о вердикте — за кодом, а не за моделью.
 *
 * В промпте написано, что «не выполнено» ставится, только когда следов работы нет
 * вовсе. Модель это правило нарушает: живой отчёт объявил «подтверждений выполнения
 * нет» по задаче, где чек-лист отмечен целиком, списано три часа и четырнадцать
 * записей истории. Просьбами это не лечится — нарушение проверяется арифметикой,
 * значит и запрет должен быть арифметическим.
 *
 * Заодно смягчаем пункты: если в целом сказать «не сделано» нельзя, то и каждый
 * отдельный «✗ не выполнено» превращается в «? подтверждения не нашёл».
 */
export function settleVerdict(r: ReviewResult, s: ReviewSources): ReviewResult {
  if (r.verdict !== 'not_done' || !hasTraces(s)) return r;
  return {
    ...r,
    verdict: 'cannot_check',
    checked: r.checked.map((c) => (c.status === 'no' ? { ...c, status: 'no_proof' as CheckStatus } : c)),
  };
}

function sourcesLine(s: ReviewSources): string {
  const parts: string[] = [];
  if (s.messages) parts.push(`сообщений: ${s.messages}`);
  if (s.attachments) parts.push(`вложений: ${s.attachments}`);
  if (s.images) parts.push(`снимков посмотрел: ${s.images}`);
  if (s.history) parts.push(`записей истории: ${s.history}`);
  if (s.checklistTotal) parts.push(`чек-лист: ${s.checklistDone ?? 0} из ${s.checklistTotal} отмечено`);
  if (s.minutes) parts.push(`учтено времени: ${Math.round(s.minutes / 60)} ч`);
  const head = parts.length
    ? `Смотрел: ${parts.join(' · ')}.`
    : 'Смотреть было нечего: в задаче нет ни переписки, ни вложений, ни истории.';
  return s.extra?.length ? `${head} Дозапросил: ${s.extra.join('; ')}.` : head;
}

/**
 * Отчёт для переписки задачи.
 *
 * Человек читает его в чате между другими сообщениями, поэтому: вердикт первой
 * строкой, шаги — списком со значком, и обязательный хвост «что посмотреть самому».
 * Проценты уверенности не показываем: цифра без объяснения создаёт ложное доверие.
 */

export function formatReview(r: ReviewResult, sources?: ReviewSources): string {
  const lines: string[] = [`${VERDICT_TITLE[r.verdict]}.`];
  if (r.summary) lines.push(r.summary);
  /*
    Строка источников — против недоверия к проверке.

    Заказчик: «проверяет некорректно». Отчёт объявлял «не выполнено», не показав, по
    чему судил, и выглядел как приговор по одному пустому чек-листу. Теперь видно,
    что именно было под рукой, и спорить можно предметно.
  */
  if (sources) lines.push(sourcesLine(sources));

  if (r.checked.length) {
    lines.push('', 'Что проверял:');
    for (const c of r.checked.slice(0, 12)) {
      const tail = c.evidence ? ` — ${c.evidence}` : '';
      lines.push(`${MARK[c.status] ?? '?'} ${c.what}${tail}`);
    }
  }
  if (r.missing.length) {
    lines.push('', 'Чего не хватает:');
    for (const m of r.missing.slice(0, 8)) lines.push(`— ${m}`);
  }
  if (r.askHuman.length) {
    lines.push('', 'Посмотрите сами:');
    for (const a of r.askHuman.slice(0, 8)) lines.push(`— ${a}`);
  }
  // Проверка ИИ — мнение, а не приёмка: решение о закрытии задачи остаётся за людьми.
  lines.push('', 'Это проверка ИИ по материалам задачи, а не приёмка работы.');
  return lines.join('\n');
}

/** Разбор ответа модели: она отвечает текстом, а не обещаниями. */
export function parseReview(raw: string): ReviewResult | null {
  const start = raw.indexOf('{');
  const end = raw.lastIndexOf('}');
  if (start < 0 || end <= start) return null;
  let obj: Record<string, unknown>;
  try { obj = JSON.parse(raw.slice(start, end + 1)); } catch { return null; }

  const verdicts = ['done', 'partial', 'not_done', 'cannot_check'];
  const verdict = verdicts.includes(String(obj.verdict)) ? String(obj.verdict) : 'cannot_check';
  const list = (v: unknown) => (Array.isArray(v) ? v.map((x) => String(x ?? '').trim()).filter(Boolean) : []);
  const statuses: CheckStatus[] = ['ok', 'no_proof', 'no', 'unclear'];
  const checked = Array.isArray(obj.checked)
    ? (obj.checked as Record<string, unknown>[]).map((c) => ({
      what: String(c?.what ?? '').trim(),
      status: (statuses.includes(String(c?.status) as CheckStatus) ? String(c?.status) : 'unclear') as CheckStatus,
      evidence: String(c?.evidence ?? '').trim(),
    })).filter((c) => c.what)
    : [];

  const summary = String(obj.summary ?? '').trim();
  // Пустой ответ выдаём за неудачу честно: «проверено» без единого слова хуже отказа.
  if (!summary && !checked.length) return null;
  return {
    verdict: verdict as ReviewResult['verdict'],
    summary,
    checked,
    missing: list(obj.missing),
    askHuman: list(obj.ask_human ?? (obj as Record<string, unknown>).askHuman),
    confidence: Number(obj.confidence) >= 0 && Number(obj.confidence) <= 1 ? Number(obj.confidence) : 0.5,
  };
}
