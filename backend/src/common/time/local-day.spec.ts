import { endOfLocalDay, startOfLocalDay } from './local-day';

/**
 * Граница «сегодня» — единственная арифметика в счётчиках, и ошибается она молча:
 * задача со сроком на вечер просто не попадёт в список дня, а человек решит,
 * что система её потеряла.
 */
describe('конец дня в часовом поясе пользователя', () => {
  const iso = (d: Date) => d.toISOString();

  it('Москва (UTC+3): день заканчивается в 20:59:59 UTC', () => {
    // 15 января, 10:00 UTC = 13:00 в Москве; getTimezoneOffset() там равен -180
    const now = new Date('2026-01-15T10:00:00.000Z');
    expect(iso(endOfLocalDay(-180, now))).toBe('2026-01-15T20:59:59.999Z');
  });

  it('поздний вечер по Москве остаётся сегодняшним днём', () => {
    // 22:30 по Москве — это ещё 15 января у человека, хотя на сервере уже 19:30 UTC
    const now = new Date('2026-01-15T19:30:00.000Z');
    expect(iso(endOfLocalDay(-180, now))).toBe('2026-01-15T20:59:59.999Z');
  });

  it('после полуночи по Москве граница переезжает на следующий день', () => {
    // 21:10 UTC = 00:10 16 января в Москве
    const now = new Date('2026-01-15T21:10:00.000Z');
    expect(iso(endOfLocalDay(-180, now))).toBe('2026-01-16T20:59:59.999Z');
  });

  it('UTC без смещения', () => {
    const now = new Date('2026-01-15T10:00:00.000Z');
    expect(iso(endOfLocalDay(0, now))).toBe('2026-01-15T23:59:59.999Z');
  });

  it('западное полушарие (UTC-5)', () => {
    // 02:00 UTC 16-го = 21:00 15-го в Нью-Йорке, день ещё не кончился
    const now = new Date('2026-01-16T02:00:00.000Z');
    expect(iso(endOfLocalDay(300, now))).toBe('2026-01-16T04:59:59.999Z');
  });

  it('мусор вместо смещения не ломает счётчики, а считается как UTC', () => {
    const now = new Date('2026-01-15T10:00:00.000Z');
    expect(iso(endOfLocalDay(NaN, now))).toBe('2026-01-15T23:59:59.999Z');
    // абсурдное смещение подрезается до допустимых 14 часов, а не уводит день на месяц
    expect(iso(endOfLocalDay(-100000, now))).toBe('2026-01-16T09:59:59.999Z');
  });
});

describe('начало дня в часовом поясе пользователя', () => {
  const iso = (d: Date) => d.toISOString();

  it('Москва (UTC+3): день начинается в 21:00 UTC предыдущих суток', () => {
    const now = new Date('2026-01-15T10:00:00.000Z');
    expect(iso(startOfLocalDay(-180, now))).toBe('2026-01-14T21:00:00.000Z');
  });

  it('сразу после полуночи по Москве начало дня уже сегодняшнее', () => {
    // 21:10 UTC 15-го = 00:10 16-го в Москве
    const now = new Date('2026-01-15T21:10:00.000Z');
    expect(iso(startOfLocalDay(-180, now))).toBe('2026-01-15T21:00:00.000Z');
  });

  it('UTC без смещения', () => {
    const now = new Date('2026-01-15T10:00:00.000Z');
    expect(iso(startOfLocalDay(0, now))).toBe('2026-01-15T00:00:00.000Z');
  });
});
