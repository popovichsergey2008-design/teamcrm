-- Дата фокуса: на какой день человек ЗАПЛАНИРОВАЛ заняться задачей.
--
-- Это не срок. Срок — обязательство перед другими, его двигают, договариваясь;
-- дата фокуса — личный план на день, её двигают свободно и молча. Раньше «Что делать
-- сегодня» набиралось только по сроку, из-за чего задача без срока не попадала в день
-- вовсе, а задача со сроком через неделю не могла быть взята в работу сегодня.
--
-- Дата, а не отметка «в сегодня»: план на завтра нужен ровно так же, как на сегодня,
-- а «вчерашнее» по этому же полю отличается от сегодняшнего и попадает в разбор хвостов.
ALTER TABLE tasks ADD COLUMN focus_date DATE NULL;

-- Выборка «мой день» — всегда по исполнителю и дате.
CREATE INDEX idx_tasks_focus_date ON tasks (tenant_id, assignee_id, focus_date)
    WHERE focus_date IS NOT NULL AND closed_at IS NULL;
