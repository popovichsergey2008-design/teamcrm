# Внутренние пометки, которые клиенту показывать нельзя (для запасной сборки ответа).
INTERNAL = re.compile(r'Борис|в коде|нужно решение|нужен пак|нужен порядок|уточнить', re.I)

warnings: list[str] = []


def clean(s) -> str:
    """Текст ячейки: без лишних пробелов по краям строк и пустых строк подряд."""
    if s is None:
        return ''
    lines = [ln.rstrip() for ln in str(s).replace('\r', '').split('\n')]
    return re.sub(r'\n{3,}', '\n\n', '\n'.join(lines)).strip()


def aliases_of(s) -> list[str]:
    seen, out = set(), []
    for a in clean(s).split(';'):
        a = a.strip()
        if a and a.lower() not in seen:
            seen.add(a.lower())
            out.append(a)
    return out


def fill_links(text: str, links: dict[str, str], rid: str) -> str:
    for k, v in links.items():
        text = text.replace(k, v)
    if '{ССЫЛКА_' in text:
        warnings.append(f'{rid}: осталась незаполненная ссылка — {text}')
    return text


def read_sheet(ws) -> list[dict]:
    rows = list(ws.iter_rows(values_only=True))
    out = []
    for i, r in enumerate(rows[1:], start=2):
        r = list(r) + [None] * 8
        rid = clean(r[0])
        if not rid:
            if any(r[:8]):
                warnings.append(f'{ws.title}, строка {i}: нет ID — пропущена')
            continue
        if not clean(r[2]) or not clean(r[4]):
            warnings.append(f'{rid}: нет вопроса или ответа — пропущен')
            continue
        out.append({
            'id': rid, 'segment': clean(r[1]), 'question': clean(r[2]),
            'aliases': aliases_of(r[3]), 'answer': clean(r[4]),
            'bucket': (clean(r[5]) or 'A').upper()[:1], 'needs_team': clean(r[7]),
        })
    return out


def read_team(ws) -> dict[str, dict]:
    team = {}
    for r in list(ws.iter_rows(values_only=True))[1:]:
        r = list(r) + [None] * 7
        rid = clean(r[1])
        if not rid:
            continue
        team[rid] = {'answer': clean(r[5]), 'facts': clean(r[6])}
    return team


def team_answer(rid: str, t: dict) -> tuple[str | None, bool]:
    """Ответ команды → (текст или None, вопрос не решён)."""
    ans, facts = t['answer'], t['facts']
    if not ans or NOT_ANSWERED.search(ans):
        return None, True
    rw = TEAM_REWRITE.get(rid)
    if rw:
        if rw[0].strip().lower() == ans.strip().lower():
            return rw[1], False
        warnings.append(f'{rid}: ответ команды изменился («{ans[:60]}») — переписку TEAM_REWRITE '
                        'не подставляю, проверьте её')
    if len(ans) >= 60 and not re.search(r'(?<![а-яё])напиши(?![а-яё])', ans.lower()):
        return ans, False  # полноценный ответ команды — как есть
    if facts:
        kept = [s for s in re.split(r'(?<=[.!?])\s+', facts) if not INTERNAL.search(s)]
        if kept:
            warnings.append(f'{rid}: ответ собран автоматически из «{ans}» + фактов — стоит перечитать')
            return f'{ans.rstrip(".")}. {" ".join(kept)}', False
    warnings.append(f'{rid}: ответ команды «{ans}» — поручение или слишком короткий, оставлен ответ таблицы')
    return None, False


def parse_handbook() -> dict[str, list[dict]]:
    """Разделы 30-faq-NN.md по номеру сегмента: заголовок, «Ещё спрашивают», ответ."""
    out: dict[str, list[dict]] = {}
    for f in sorted(HANDBOOK.glob('30-faq-*.md')):
        seg = f.stem.split('-')[-1]
        items = []
        for blk in re.split(r'\n## ', f.read_text(encoding='utf-8'))[1:]:
            lines = blk.split('\n')
            body = [ln for ln in lines[1:] if ln.strip()
                    and not ln.startswith('Ещё спрашивают') and not ln.startswith('![')]
            items.append({'title': lines[0].strip(), 'answer': '\n'.join(body).strip(), 'file': f})
        out[seg] = items
    return out


def patch_handbook(file: Path, title: str, answer: str) -> None:
    """Заменить ответ под заголовком «## title», не трогая «Ещё спрашивают» и снимок."""
    text = file.read_text(encoding='utf-8')
    parts = re.split(r'(\n## )', text)
    for i in range(2, len(parts), 2):
        lines = parts[i].split('\n')
        if lines[0].strip() != title:
            continue
        keep_head = [lines[0], '']
        alias = next((ln for ln in lines[1:] if ln.startswith('Ещё спрашивают')), None)
        if alias:
            keep_head += [alias, '']
        imgs = [ln for ln in lines[1:] if ln.startswith('![')]
        tail = (['', *imgs] if imgs else [])
        trailing = re.search(r'\s*$', parts[i]).group()  # отступ до следующего раздела — как был
        parts[i] = '\n'.join(keep_head + [answer] + tail) + trailing
        file.write_text(''.join(parts), encoding='utf-8')
        return
    warnings.append(f'справка: не нашёл «{title}» в {file.name}')


def build(xlsx: Path) -> None:
    wb = openpyxl.load_workbook(xlsx, data_only=True)
    site = read_sheet(wb['Сайт'])
    app = read_sheet(wb['Приложение'])
    team = read_team(wb['Вопросы к команде'])
    known = {r['id'] for r in site + app}
    for rid in team:
        if rid not in known:
            warnings.append(f'«Вопросы к команде»: {rid} нет на листах «Сайт»/«Приложение»')

    stats = {'site': 0, 'site_handoff': 0, 'app': 0, 'app_handoff': 0,
             'team_used': 0, 'site_fixed': 0, 'app_from_handbook': 0, 'handbook_patched': 0}

    # ── Сайт ──
    answers = []
    for r in site:
        handoff, text = False, r['answer']
        if r['id'] in team:
            t, unresolved = team_answer(r['id'], team[r['id']])
            if unresolved:
                handoff = True
            elif t:
                text = t
                stats['team_used'] += 1
        elif r['id'] in SITE_FIXES:
            mark, fixed = SITE_FIXES[r['id']]
            if mark in text:
                text = fixed
                stats['site_fixed'] += 1
            else:
                warnings.append(f'{r["id"]}: в таблице ответ уже поправлен — SITE_FIXES не нужен')
        seg = r['segment'][:3]
        if handoff:
            text = HANDOFF_SITE
            actions = [{'type': 'support', 'label': 'Позвать инженера'}]
            stats['site_handoff'] += 1
        elif seg == '06.':
            actions = [{'type': 'migration', 'label': 'Бесплатный переезд'}]
        elif seg == '17.':  # «Передача человеку»: человек просит живого собеседника
            actions = [{'type': 'support', 'label': 'Позвать инженера'}]
        else:
            actions = [{'type': 'signup', 'label': 'Зарегистрироваться'}]
        answers.append({'id': r['id'], 'title': r['question'], 'aliases': r['aliases'],
                        'answer': fill_links(text, LINKS_SITE, r['id']), 'actions': actions})
    stats['site'] = len(answers)
    SITE_OUT.write_text(json.dumps({'version': 1, 'answers': answers}, ensure_ascii=False, indent=2)
                        + '\n', encoding='utf-8')

    # ── Приложение ──
    hb = parse_handbook()
    by_seg: dict[str, list[dict]] = {}
    for r in app:
        by_seg.setdefault(r['segment'][:2], []).append(r)
    hb_of: dict[str, dict] = {}
    for seg, rows in by_seg.items():
        items = hb.get(seg, [])
        if len(items) == len(rows):
            # Разделы справки идут в том же порядке, что строки сегмента: сопоставляем по
            # месту — часть вопросов в справке переименована вместе с исправленным ответом.
            hb_of.update({r['id']: it for r, it in zip(rows, items)})
        else:
            titles = {it['title']: it for it in items}
            hb_of.update({r['id']: titles[r['question']] for r in rows if r['question'] in titles})
            warnings.append(f'справка, сегмент {seg}: {len(items)} разделов на {len(rows)} строк — '
                            'сопоставлено по заголовкам')

    entries = []
    for r in app:
        handoff, text, question = False, r['answer'], r['question']
        aliases = list(r['aliases'])
        h = hb_of.get(r['id'])
        hb_differs = bool(h and h['answer'].replace('\n', ' ') != r['answer'].replace('\n', ' '))
        team_text = None
        if r['id'] in team and not (r['id'] in PRODUCT_WINS and hb_differs):
            team_text, handoff = team_answer(r['id'], team[r['id']])
        # Ответ команды проверяется раньше справки: справку скрипт сам же и правит ответами
        # команды, и при следующем запуске она не должна перебить обновлённый ответ.
        if handoff:
            text = HANDOFF_APP
            stats['app_handoff'] += 1
        elif team_text:
            text = team_text
            stats['team_used'] += 1
            if h and h['answer'] != team_text:
                patch_handbook(h['file'], h['title'], team_text)
                stats['handbook_patched'] += 1
        elif hb_differs:
            text = h['answer']
            stats['app_from_handbook'] += 1
        if h and h['title'] != question:
            # Вопрос в справке переформулирован под нынешний продукт — старая формулировка
            # остаётся синонимом: люди спрашивают и так.
            aliases.insert(0, question)
            question = h['title']
        entries.append({'id': r['id'], 'segment': r['segment'], 'question': question,
                        'aliases': aliases, 'answer': fill_links(text, LINKS_APP, r['id']),
                        'bucket': r['bucket'], 'handoff': handoff})
    stats['app'] = len(entries)
    APP_OUT.write_text(json.dumps(entries, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')

    for k, v in stats.items():
        print(f'{k}: {v}')
    for w in warnings:
        print('ВНИМАНИЕ:', w)


if __name__ == '__main__':
    sys.stdout.reconfigure(encoding='utf-8')
    if len(sys.argv) != 2:
        sys.exit('Использование: python -I scripts/qa-base/build_qa.py таблица.xlsx')
    build(Path(sys.argv[1]))
