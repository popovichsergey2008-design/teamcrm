Исполнитель. Человек называется после «на», «для», «поручи», «назначь» или просто по имени: «поставь на Константина», «Алине — смету». Сопоставь с users и верни assigneeId. Имя в тексте обычно в косвенном падеже («Константина», «Юрию») — это тот же человек. Если подходящих несколько или совпадения нет — null.

