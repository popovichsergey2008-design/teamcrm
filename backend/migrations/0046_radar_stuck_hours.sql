-- Порог «зависшего на проверке» — личная настройка руководителя.
--
-- Было жёстко зашито 48 часов. Для одних команд это вечность (задачи проверяют в тот же
-- день), для других — норма. Единого правильного числа нет, поэтому оно переехало в
-- личный кабинет того, кто смотрит «Пульс команды».
--
-- NULL означает «как по умолчанию» (24 часа), а не «выключено»: так изменение значения
-- по умолчанию в коде не придётся разносить UPDATE'ом по всем строкам.
ALTER TABLE users ADD COLUMN radar_stuck_hours SMALLINT NULL
    CHECK (radar_stuck_hours IS NULL OR (radar_stuck_hours BETWEEN 1 AND 168));
