-- Личная настройка интерфейса: порядок и видимость пунктов левого меню.
--
-- Хранится у ПОЛЬЗОВАТЕЛЯ, а не в браузере: человек садится за другой компьютер,
-- заходит с ноутбука из дома — и меню должно остаться тем, которое он себе собрал.
-- В localStorage такая настройка живёт до первой смены устройства и воспринимается
-- как «сбросилось само».
--
-- JSONB, а не таблица со строками на каждый пункт: это цельная настройка одного
-- человека, её читают и пишут целиком, и разбирать её на строки — лишняя работа
-- ради данных, которые никто не запрашивает по отдельности.
ALTER TABLE users ADD COLUMN ui_prefs JSONB NOT NULL DEFAULT '{}'::jsonb;
