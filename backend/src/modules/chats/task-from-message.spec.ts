import { referential, withSource } from './chat-task-draft.service';

describe('#4895: задача из сообщения — без чужих реплик', () => {
  it('самостоятельная просьба соседей не берёт, ссылочная — берёт', () => {
    expect(referential('и еще мета прописать новым страницам кево нужно https://docs.google.com/spreadsheets/d/1CUrf')).toBe(false);
    expect(referential('что-то напоминалка не работает, я ничего не видел сегодня, а у тебя что-то писало?')).toBe(false);
    expect(referential('да, и там же поправь шрифт в шапке страницы тарифов')).toBe(true);
    expect(referential('это тоже')).toBe(true);
  });
  it('исходное сообщение — в описании дословно', () => {
    expect(withSource('Добавить описание задачи', 'а что за риск срыва срока? точка зелёная')).toContain('«а что за риск срыва срока? точка зелёная»');
    expect(withSource('Риск срыва срока: а что за риск срыва срока?', 'а что за риск срыва срока?')).toBe('Риск срыва срока: а что за риск срыва срока?');
  });
});
