-- Внешняя ссылка, привязанная к чату.
--
-- Гостевые ссылки жили только в разделе встреч и были «сами по себе»: выдал ссылку —
-- и помни, кому и зачем. На практике внешнего человека зовут в разговор по конкретной
-- теме, а тема в системе — это чат: с клиентом, по проекту, с подрядчиком.
--
-- Комнату не меняем: ссылка по-прежнему держит свою переговорную (комнаты SFU живут
-- в памяти, а ссылку отправляют заранее). Привязка к чату — это ответ на вопрос
-- «для какого разговора она». По ней в шапке чата видно, что внешняя ссылка уже есть,
-- и сотрудник одним нажатием заходит в ТУ ЖЕ комнату, куда придёт гость.
ALTER TABLE meet_guest_links
    ADD COLUMN chat_id BIGINT NULL REFERENCES chats(id) ON DELETE SET NULL;

CREATE INDEX idx_meet_guest_links_chat ON meet_guest_links (tenant_id, chat_id)
    WHERE chat_id IS NOT NULL AND revoked_at IS NULL;
