/**
 * Деление быстрой команды на отдельные поручения БЕЗ модели (ТЗ-10, этап 1).
 *
 * Обычно поручения разделяет ИИ. Но модель может не ответить — кончились деньги,
 * провайдер лёг, ключ не заведён, — и тогда три поручения склеивались в одну задачу
 * с заголовком во всю фразу: «Проверить форму регистрации до пятницы. Вторая задача:
 * написать текст для лендинга. Третья: обновить документацию». Человек получал одну
 * бессмысленную задачу вместо трёх и не понимал, почему.
 *
 * Правилами берём только то, что человек написал ЯВНО: нумерацию («1.», «2)»),
 * слова-разделители («вторая задача», «также», «ещё»), перечисление с новой строки.
 * Обычную точку между предложениями разделителем НЕ считаем — иначе «Проверить форму.
 * Она не работает на телефоне» превратится в две задачи, и это хуже, чем одна.
 *
 * Не угадываем: не уверены — отдаём одну строку целиком, дальше работает прежний путь.
 *
 * Чистые функции; проверяются юнит-тестом рядом.
 */

/** Сколько поручений имеет смысл разбирать за раз. Столько же, сколько у модели. */
const MAX_PARTS = 10;
/** Короче этого кусок — не поручение, а обрывок: «и всё», «спасибо». */
const MIN_PART = 12;

/*
  Кириллица в JS-регулярках не знает `\b` и `\w` — границы слов пишем вручную
  (см. память voice-and-nl). Окончания слов ловим через `[а-я]*`.
*/
const ORDINALS = 'перв|втор|трет|четверт|пят|шест|седьм|восьм|девят|десят';
/*
  «Вторая задача:», «третье поручение —», «2) », «3. », а также голое «Третья: …» —
  порядковое слово со знаком после него: так пишут чаще всего. Без знака
  («Первая попытка не удалась») разделителем НЕ считаем — это продолжение мысли.
*/
const ORDINAL_MARK = `(?:${ORDINALS})[а-я]*(?:\\s+(?:задач|поручен)[а-я]*)?\\s*[:—–-]`;
const NUMBERED = new RegExp(`^\\s*(?:\\d{1,2}\\s*[).:-]|${ORDINAL_MARK})\\s*`, 'i');
/** Слова, с которых человек начинает СЛЕДУЮЩЕЕ поручение. */
const STARTERS = new RegExp(
  `^\\s*(?:(?:а\\s+)?(?:(?:${ORDINALS})[а-я]*\\s+(?:задач|поручен)[а-я]*|${ORDINAL_MARK})`
  + '|(?:и\\s+)?(?:также|ещё|еще)(?![а-яa-z])'
  + '|(?:а\\s+)?(?:потом|затем|далее)(?![а-яa-z])'
  + '|\\d{1,2}\\s*[).:-])',
  'i',
);

/** Убрать номер или «вторая задача:» из начала куска — в заголовке они лишние. */
export function stripMarker(part: string): string {
  return part.replace(NUMBERED, '').replace(/^[\s—–-]+/, '').trim();
}

/**
 * Разделить команду на поручения. Вернёт одну строку, если явных разделителей нет:
 * это значит «делить нечего», а не «деление не удалось».
 */
export function splitCommand(text: string): string[] {
  const clean = (text ?? '').trim();
  if (clean.length < MIN_PART) return clean ? [clean] : [];

  // 1. Перечисление строками — самый явный случай: человек сам расставил пункты.
  const lines = clean.split(/\r?\n+/).map((l) => l.trim()).filter(Boolean);
  if (lines.length > 1) {
    const numbered = lines.filter((l) => NUMBERED.test(l)).length;
    // Либо пронумерованы почти все, либо это просто список коротких строк.
    if (numbered >= lines.length - 1 || lines.every((l) => l.length >= MIN_PART)) {
      const parts = lines.map(stripMarker).filter((p) => p.length >= MIN_PART);
      if (parts.length > 1) return parts.slice(0, MAX_PARTS);
    }
  }

  // 2. Одной строкой: режем по границам предложений и склеиваем обратно всё,
  //    что не начинается со слова-разделителя. Точка сама по себе не делит.
  const sentences = clean.split(/(?<=[.!?;])\s+/).map((s) => s.trim()).filter(Boolean);
  if (sentences.length < 2) return [clean];

  const parts: string[] = [];
  for (const sentence of sentences) {
    const starts = STARTERS.test(sentence);
    if (!parts.length || !starts) {
      if (!parts.length) parts.push(sentence);
      else parts[parts.length - 1] = `${parts[parts.length - 1]} ${sentence}`.trim();
      continue;
    }
    parts.push(sentence);
  }

  // Хвостовая точка или точка с запятой в заголовке не нужны: это след разделителя, а не текст.
  const cleaned = parts.map(stripMarker).map((p) => p.replace(/[;,.\s]+$/, '')).filter((p) => p.length >= MIN_PART);
  return cleaned.length > 1 ? cleaned.slice(0, MAX_PARTS) : [clean];
}
