/**
 * Поле на экране и то же поле на сервере: чьё значение показывать.
 *
 * Обе ошибки, ради которых это вынесено, выглядели одинаково — «нажал, а ничего не
 * поменялось», — и обе молча портили данные. Поэтому правила здесь, рядом с проверками
 * (scripts/logic-check.mjs), а не размазаны по компонентам.
 */

/**
 * Следовать ли полю за новым значением с сервера (#4652).
 *
 * Правило: человек поле не трогал (в нём ровно то, что сервер присылал прошлый раз) —
 * показываем новое; правил — оставляем набранное. Прошлое серверное значение передаётся
 * ЯВНО: раньше его читали из ref внутри отложенного setState, а ref к тому моменту уже
 * указывал на новое значение. Поле считалось «правленым», оставалось со старым сроком,
 * кнопка сохранения загоралась — и «Сохранить» возвращал задаче старый срок.
 */
export function followServer<T>(current: T, prevServer: T, nextServer: T): T {
  return current === prevServer ? nextServer : current;
}

/**
 * Свежий ответ сервера поверх несохранённых правок человека (#4645).
 *
 * Черновик дописывает сервер (ИИ, ответ автора о проекте) и рассылает событием; пока
 * человек набирает текст, каждое такое событие затирало набранное. Правки человека
 * важнее: поля, которые он менял и которые ещё не сохранены, берём у него.
 */
export function overServer<T extends object>(server: T, edits: Partial<T>): T {
  return { ...server, ...edits };
}

/**
 * Какие правки остались несохранёнными после ответа на отправку `sent`.
 *
 * Поле, которое человек успел поменять ещё раз, пока шёл запрос, остаётся правкой:
 * сервер сохранил прошлое значение, а не то, что сейчас в поле.
 */
export function settleEdits<T extends object>(edits: Partial<T>, sent: Partial<T>): Partial<T> {
  const left: Partial<T> = { ...edits };
  for (const key of Object.keys(sent) as (keyof T)[]) {
    if (key in left && same(left[key], sent[key])) delete left[key];
  }
  return left;
}

function same(a: unknown, b: unknown): boolean {
  if (a === b) return true;
  // чек-лист и разложенные поручения — массивы; сравниваем по содержимому, не по ссылке
  return Array.isArray(a) && Array.isArray(b) && JSON.stringify(a) === JSON.stringify(b);
}
