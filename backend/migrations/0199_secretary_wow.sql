-- #1525 «ВАУ-эффект ИИ-секретаря»: охотник за обещаниями и утренний аудио-кофе.
--
-- 1. «Напомнить мне завтра» на карточке обещавшего: когда прислать ему напоминание.
--    Отдельная колонка, а не check_at: проверка обещания и личное напоминание живут
--    своими сроками, и одно не должно сдвигать другое.
ALTER TABLE commitments ADD COLUMN IF NOT EXISTS self_remind_at TIMESTAMPTZ NULL;

-- 2. Утренний аудио-кофе владельцу и руководителям — в 9:00 по поясу человека без
--    всякой настройки (документ: «В 9:00 утра … шефа ждёт аудиозаметка»). NULL —
--    человек выключил. Раньше бриф приходил только следом за утренней сводкой, время
--    которой по умолчанию не задано, и до большинства руководителей не доходил вовсе.
ALTER TABLE secretary_prefs ADD COLUMN IF NOT EXISTS brief_at TIME NULL DEFAULT '09:00';

-- Кто уже выставил время утренней сводки — бриф приходил вместе с ней; не ломаем:
-- оставляем ему то же время, а не переводим на 9:00.
UPDATE secretary_prefs SET brief_at = morning_at WHERE morning_at IS NOT NULL;
