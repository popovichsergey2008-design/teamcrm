-- Разовая починка имён файлов, испорченных при загрузке.
--
-- Браузер шлёт имя вложения в UTF-8, а multipart-разбор отдавал его побайтово как
-- latin1, поэтому «условия.txt» лежит в базе как «ÑÑÐ»Ð¾Ð²Ð¸Ñ.txt». Сама причина
-- устранена в коде (decodeUploadName), но уже загруженные файлы остались с мусором
-- в названии — а теперь они попали в поиск, и это видно всем.
--
-- Почему миграцией, а не скриптом по SSH: она применится на проде сама при деплое,
-- её нельзя забыть запустить, и факт применения зафиксирован в schema_migrations.
--
-- Правим ТОЛЬКО отображаемое имя (files.file_name). object_key — это ключ объекта
-- в хранилище, файл лежит там именно под ним; переименование объекта означало бы
-- копирование содержимого с риском потерять его на полпути ради косметики.
--
-- ЧТО ВОССТАНОВИТЬ НЕЛЬЗЯ. Санитизация имени заменяла непечатаемые символы на «_»
-- ещё до записи в базу, и у части имён вторые байты кириллических пар физически
-- потеряны: «Ñ_Ñ_Ð_Ð¾Ð²Ð_Ñ_.txt» = байты d1 5f d1 5f d0 5f… Такую строку не
-- расшифровать ничем — угадывать буквы мы не станем. Эти имена останутся как есть,
-- и в NOTICE будет видно, сколько строк удалось починить, а сколько пропущено.
DO $$
DECLARE
  r       RECORD;
  fixed   TEXT;
  n       INT := 0;
  skipped INT := 0;
BEGIN
  -- Берём только имена с многобайтовыми символами: у чистой латиницы чинить нечего.
  FOR r IN SELECT id, file_name FROM files WHERE octet_length(file_name) <> char_length(file_name)
  LOOP
    BEGIN
      -- Обратная операция к тому, что произошло при загрузке. Для ПРАВИЛЬНОГО имени
      -- («Отчёт.docx») этот вызов упадёт: кириллица не представима в latin1 — и такая
      -- строка будет пропущена, что нам и нужно.
      fixed := convert_from(convert_to(r.file_name, 'LATIN1'), 'UTF8');
    EXCEPTION WHEN OTHERS THEN
      -- Имя либо уже верное (кириллица не представима в latin1), либо испорчено
      -- необратимо — в обоих случаях не трогаем.
      skipped := skipped + 1;
      CONTINUE;
    END;

    IF fixed IS DISTINCT FROM r.file_name AND length(btrim(fixed)) > 0 THEN
      UPDATE files SET file_name = fixed WHERE id = r.id;
      n := n + 1;
    END IF;
  END LOOP;

  RAISE NOTICE 'имена файлов: починено %, пропущено % (верные или невосстановимые)', n, skipped;
END $$;
