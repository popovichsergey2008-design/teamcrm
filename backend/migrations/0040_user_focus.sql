-- Текущий фокус сотрудника: над чем человек работает прямо сейчас и до какого времени.
--
-- Зачем отдельная таблица, когда уже есть user_availability: та про календарь
-- (отпуск, больничный, график), она отвечает на вопрос «доступен ли на неделе».
-- Фокус — про ближайший час: «Работаю над макетом до 16:00, не дёргайте».
-- Смешивать их нельзя: у них разный срок жизни и разные последствия.
--
-- Строки может не быть вовсе — это нормальное состояние «свободен», и заводить
-- запись для каждого сотрудника заранее незачем.
CREATE TABLE user_focus (
    tenant_id  BIGINT NOT NULL REFERENCES tenants(id),
    user_id    BIGINT NOT NULL REFERENCES users(id),
    -- deep — глубокий фокус, call — созвон, quick — разбираю почту и чаты,
    -- break — перерыв, task — автоматически при старте таймера по задаче
    kind       VARCHAR(12) NOT NULL,
    note       VARCHAR(160) NULL,                   -- «Работаю над макетом»
    task_id    BIGINT NULL REFERENCES tasks(id) ON DELETE SET NULL,
    -- До какого момента фокус действует. NULL — до отмены руками.
    -- Просроченный фокус не показываем и не удаляем немедленно: сравнение с now()
    -- при чтении надёжнее любого расписания, которое может не отработать.
    until      TIMESTAMPTZ NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (tenant_id, user_id)
);

-- Список фокусов организации нужен целиком (кто чем занят), поэтому индекс
-- по сроку годности: строки с истёкшим until отфильтровываются при выборке.
CREATE INDEX idx_user_focus_until ON user_focus (tenant_id, until);
