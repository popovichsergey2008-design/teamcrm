-- Объединение похожих задач.
--
-- Дубли заводятся сами собой: один написал «добавить чат в карточку», другой через
-- неделю — «сделать обсуждение внутри задачи». Обе живут, обе кто-то делает, и
-- узнаётся это в лучшем случае на разборе.
--
-- Объединение НЕ удаляет вторую задачу. Она остаётся с пометкой «объединена» и
-- ссылкой на основную: по её номеру уже сослались в переписке и в отчётах, и
-- ссылка, ведущая в никуда, хуже лишней строки в списке. Переписка, файлы и люди
-- переезжают в основную, история остаётся у обеих — кто и что делал, видно всегда.
ALTER TABLE tasks
    ADD COLUMN merged_into_id BIGINT NULL REFERENCES tasks(id),
    ADD COLUMN merged_at      TIMESTAMPTZ NULL,
    ADD COLUMN merged_by      BIGINT NULL REFERENCES users(id);

-- Обратный вопрос «что сюда объединили» задаётся в карточке основной задачи.
CREATE INDEX idx_tasks_merged_into ON tasks (tenant_id, merged_into_id)
    WHERE merged_into_id IS NOT NULL;
