-- Пересылка сообщений между чатами (просьба заказчика: «как в Telegram»).
--
-- Пересылают, чтобы показать чужие слова своей командой: «вот что написал клиент».
-- Значит, у пересланного обязан быть виден АВТОР ОРИГИНАЛА — иначе это выглядит как
-- собственные слова того, кто переслал, и разговор идёт не о том.
--
-- Имя автора храним строкой, а не ссылкой на человека: пересланное живёт годами, а
-- сотрудник может уйти и быть удалён — подпись «Переслано от …» не должна пропасть
-- вместе с ним. Ссылка на исходное сообщение тоже есть: у кого есть доступ к тому
-- чату, тот сможет открыть первоисточник.
ALTER TABLE chat_messages
    ADD COLUMN IF NOT EXISTS forwarded_from_id BIGINT NULL REFERENCES chat_messages(id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS forwarded_author  TEXT   NULL,
    -- Из какого чата переслали: по нему решаем, показывать ли ссылку «к оригиналу».
    ADD COLUMN IF NOT EXISTS forwarded_chat_id BIGINT NULL REFERENCES chats(id) ON DELETE SET NULL;
