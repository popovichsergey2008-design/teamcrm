-- Ежедневные отложенные сообщения.
--
-- Заказчик: «нету каждый день в определённое время... просто каждый день и поле
-- время, или календарь и поле время, и всё». Готовые варианты («через час»,
-- «завтра утром») он не просил — они угадывают за человека, а человек обычно
-- знает точное время: за полчаса до планёрки, в девять утра каждый день.
--
-- Два режима, больше не нужно:
--   none  — один раз в назначенный момент (как было);
--   daily — каждый день в это же время.
--
-- Повтор живёт в ТОЙ ЖЕ строке: отправив, планировщик двигает время на сутки
-- вперёд, а не заводит новую запись. Иначе за месяц накопится тридцать строк об
-- одном и том же напоминании, и список отложенных станет нечитаемым.
ALTER TABLE chat_scheduled
    ADD COLUMN repeat_kind VARCHAR(8) NOT NULL DEFAULT 'none',
    -- Сколько раз уже ушло: по нему видно, что повтор действительно работает.
    ADD COLUMN sent_count INT NOT NULL DEFAULT 0;
