import { snippet } from './search.service';
import { SearchRepository } from './search.repository';

/**
 * Две мелочи, которые ошибаются молча: окрестность совпадения (человек видит начало
 * чужого разговора вместо того, что искал) и экранирование шаблона LIKE (запрос «100%»
 * превращается в «найди вообще всё»).
 */
describe('поиск: подготовка строк', () => {
  it('показывает окрестность найденного слова, а не начало сообщения', () => {
    const body = 'Начало разговора ни о чём. '.repeat(6) + 'договор 415-А подписан' + ' и дальше ещё текст'.repeat(4);
    const s = snippet(body, 'договор');
    expect(s).toContain('договор 415-А');
    expect(s.startsWith('…')).toBe(true); // начало обрезано — совпадение было в середине
    expect(s.length).toBeLessThan(200);
  });

  it('короткое сообщение показывает целиком, без многоточий', () => {
    expect(snippet('Готово, залил', 'залил')).toBe('Готово, залил');
  });

  it('схлопывает переносы строк: в списке строка одна', () => {
    expect(snippet('первая\n\n   вторая', 'вторая')).toBe('первая вторая');
  });

  it('если совпадения нет (регистр, форма слова) — отдаёт начало, а не пустоту', () => {
    expect(snippet('Текст без совпадения', 'ничего')).toContain('Текст без совпадения');
  });

  it('спецсимволы LIKE экранируются: «100%» ищет проценты, а не «всё подряд»', () => {
    expect(SearchRepository.like('100%')).toBe('%100\\%%');
    expect(SearchRepository.like('a_b')).toBe('%a\\_b%');
    expect(SearchRepository.like('c:\\tmp')).toBe('%c:\\\\tmp%');
  });
});
