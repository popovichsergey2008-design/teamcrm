-- ТЗ-21, этап 0: кэш ответов ИИ — по набору прав, а не на всю компанию.
--
-- Раньше смысловой кэш «Мозга» был общим на организацию: ответ, собранный из закрытого
-- проекта, мог получить сотрудник, который этот проект не видит. Теперь у ответа есть ключ
-- доступа (all · public · хэш видимых закрытых проектов), и ищут только среди своих.
-- Старые ответы ключа не имеют и больше не совпадут ни с кем — их проще удалить.
ALTER TABLE ai_answer_cache ADD COLUMN IF NOT EXISTS access_key VARCHAR(40) NOT NULL DEFAULT 'legacy';
DELETE FROM ai_answer_cache WHERE access_key = 'legacy';
